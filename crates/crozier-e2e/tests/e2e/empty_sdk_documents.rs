//! The documents the certified pair turns into an empty SDK, and the shapes
//! beside them the pair really generates, each in a document written for it
//! under `docs/fern-measurements/handed-off/empty-sdk-documents/` (triaged in
//! `docs/fern-measurements/handed-off/empty-sdk-documents.tsv`), driven through
//! the real binary.
//!
//! - Under the user's ruling `empty-sdk-refused` (2026-11-01), every document
//!   whose certified-pair outcome is the 35-file empty scaffold over a document
//!   it never parsed is refused, by default and under `--fern-strict`, by the
//!   class the pair's own error names, writing nothing.
//! - lolesports' shape (a required property that is an `allOf` of its own
//!   schema and a nullable object) is valid OpenAPI the pair's example builder
//!   overflows on; it keeps generating, the tree its measurement records.
//! - A header `$ref` into another operation's response headers, and a schema
//!   `$ref` naming a relative file that does not exist, are generated by the
//!   pair in full, so crozier generates Fern's tree from them.

use std::path::{Path, PathBuf};

use predicates::prelude::*;

use super::{departure_ledger, golden_tree_failures, probe_command, repo_root};

pub(crate) const EMPTY_SDK_DIR: &str = "docs/fern-measurements/handed-off/empty-sdk-documents";
/// The measurements whose `fern-expected/` crozier is compared with whole; the
/// others' trees are the pair's empty scaffold, the evidence of its refusal.
pub(crate) const GENERATED_CASES: [&str; 2] =
    ["crozier-refuses-path-pointer-ref", "missing-relative-file"];
const SCAFFOLD_FILES: usize = 35;

fn case_dir(case: &str) -> PathBuf {
    repo_root().join(EMPTY_SDK_DIR).join(case)
}

fn read(path: &Path) -> String {
    std::fs::read_to_string(path).unwrap_or_else(|error| panic!("{}: {error}", path.display()))
}

fn file_count(tree: &Path) -> usize {
    walkdir(tree).len()
}

fn walkdir(tree: &Path) -> Vec<PathBuf> {
    let mut files = Vec::new();
    let mut pending = vec![tree.to_path_buf()];
    while let Some(directory) = pending.pop() {
        for entry in std::fs::read_dir(&directory)
            .unwrap_or_else(|error| panic!("{}: {error}", directory.display()))
        {
            let path = entry.unwrap().path();
            if path.is_dir() {
                pending.push(path);
            } else {
                files.push(path);
            }
        }
    }
    files.sort();
    files
}

/// The committed log records the pair's false success: generation exits 0
/// while the log reads `Failed to parse openapi document` and the phrase the
/// class's template names. Callers count the scaffold's files apart.
fn assert_log_records_false_success(case: &str, log: &str, phrase: &str) {
    let log = read(&case_dir(case).join(log));
    assert!(
        log.contains("generate exit: 0")
            && log.contains("Failed to parse openapi document")
            && log.contains(phrase),
        "{case}: the committed log no longer records the pair's empty SDK:\n{log}"
    );
}

/// crozier refuses `spec` by default and under `--fern-strict`, naming `class`
/// and `element` and writing nothing.
fn assert_refused(spec: &Path, class: &str, element: &str) {
    for strict in [false, true] {
        let temp = tempfile::tempdir().expect("output tempdir");
        let out = temp.path().join("sdk");
        let mut command = probe_command(spec, &out);
        if strict {
            command.arg("--fern-strict");
        }
        command.assert().failure().stderr(
            predicate::str::contains(format!("{class}: ")).and(predicate::str::contains(element)),
        );
        assert!(
            !out.exists(),
            "{} (strict {strict}): a refused document writes no SDK",
            spec.display()
        );
    }
}

