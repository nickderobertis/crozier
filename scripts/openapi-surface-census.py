#!/usr/bin/env python3
"""Census the OpenAPI surface every registered golden source *declares*.

`just fixtures-coverage` answers what the goldens reach in `src/`, and
`just fixtures-gaps` answers which generated bytes still diverge. Neither answers
the question this instrument exists for: **which OpenAPI shapes has the corpus
ever seen?** A shape no registered source declares is generator behaviour only
crozier vouches for — the gate stays green whatever crozier does with it — so
knowing the list is the first step to closing it
(`docs/openapi-surface-coverage.md`).

Three rules make the number honest; none of them a `grep` obeys.

* **Source documents only, never generated output.** A specification is what
  *declares* a feature; the emitted Python is not. A census that read an
  `expected/` tree would be measuring the answer instead of the question, so the
  only files opened here are the vendored `tests/fixtures/<name>/openapi.*`
  documents and the `link-ok` documents `scripts/fetch-corpus.sh` fetches into
  `.local/corpus/<name>/` from `tests/fixtures/CORPUS.md`.
* **The OpenAPI object model, not the text.** A text match scores a `trace`
  operation off a path parameter named `trace`, a `name` field off a schema
  property called `name`, and a `type` field off a property called `type` — all
  three shapes are in the vendored corpus today. The walk below knows the keys of
  a Schema Object's `properties` are *names*, the keys of a Paths Object are path
  templates, and the keys of a Responses Object are status codes, so none of them
  can be mistaken for a declared field. Free-form values (`example`, `examples`,
  `default`, `enum`, `const`) are never descended into for the same reason.
* **An unfetched source is a hard failure, not a silent skip.** A `link-ok` row
  whose spec has not been fetched would otherwise report as declaring nothing,
  and 93 of the 124 registered sources are `link-ok`. Pass `--allow-unfetched`
  to downgrade that to a warning, or `--vendored-only` to census the offline half
  on purpose.

The selector grammar, the region boundaries and how a census result becomes a
classified row are `docs/openapi-surface-coverage.md`; they are not restated
here. What only this file knows is the object-model table itself — `OBJECTS`
below is the machine-readable half of that grammar.
"""

