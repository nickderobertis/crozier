# ---------------------------------------------------------------------------
# Reading a source document
# ---------------------------------------------------------------------------
#
# The corpus is half JSON and half YAML, and this script has to run inside
# `just check` on the Linux/macOS/Windows matrix with nothing but the standard
# library — the gate installs no Python packages, so PyYAML is not available.
# The loader below therefore reads the block-YAML subset OpenAPI documents are
# written in (mappings, sequences, the three scalar styles, block scalars,
# anchors/aliases/merge keys, flow collections) and REFUSES anything else by
# name and line. Refusing is the point: a census built on a loader that guessed
# would be wrong quietly, which is the one failure mode the instrument cannot
# have.


class DocumentError(Exception):
    """A source document this census cannot read, with the site that stopped it."""

    def __init__(self, path: Path, line: int, message: str) -> None:
        super().__init__(f"{path}:{line}: {message}")
        self.path = path
        self.line = line


_NULL = {"", "~", "null", "Null", "NULL"}
_TRUE = {"true", "True", "TRUE"}
_FALSE = {"false", "False", "FALSE"}
_INT = re.compile(r"[-+]?[0-9]+$")
_FLOAT = re.compile(r"[-+]?(?:[0-9]*\.[0-9]+|[0-9]+\.[0-9]*)(?:[eE][-+]?[0-9]+)?$")
_EXP = re.compile(r"[-+]?[0-9]+[eE][-+]?[0-9]+$")
# A block-mapping key ends at the first ':' that is followed by a space or the
# end of the line: `https://example.test: v` is one key, and `application/json:`
# is another. Anything else (a URL's `://`, a `{$request.body#/x}` template) is
# part of the key or of the value.
_KEY_END = re.compile(r":(?=\s|$)")
_ESCAPES = {
    "0": "\0", "a": "\a", "b": "\b", "t": "\t", "\t": "\t", "n": "\n",
    "v": "\v", "f": "\f", "r": "\r", "e": "\x1b", " ": " ", '"': '"',
    "/": "/", "\\": "\\", "N": "\x85", "_": "\xa0",
}


@dataclass(frozen=True)
class _Line:
    """One significant source line: its index, indentation and comment-free text."""

    index: int
    indent: int
    text: str


class _YamlReader:
    """A strict reader for the block-YAML subset OpenAPI documents are written in."""

    def __init__(self, path: Path, text: str) -> None:
        self.path = path
        self.lines = text.replace("\r\n", "\n").replace("\r", "\n").split("\n")
        if self.lines and self.lines[-1] == "":
            self.lines.pop()  # the file's terminating newline is not a line
        self.pos = 0
        self.anchors: dict[str, Any] = {}

    def fail(self, index: int, message: str) -> None:
        raise DocumentError(self.path, index + 1, message)

    @staticmethod
    def strip_comment(text: str) -> str:
        """Drop a trailing `#` comment, honoring quotes (`$ref: "#/x"` is not one)."""
        quote = ""
        cursor = 0
        while cursor < len(text):
            char = text[cursor]
            if quote:
                if char == "\\" and quote == '"':
                    cursor += 2  # an escape: the next character cannot close the quote
                    continue
                if char == quote:
                    quote = ""
            elif char in "\"'":
                quote = char
            elif char == "#" and (cursor == 0 or text[cursor - 1] in " \t"):
                return text[:cursor]
            cursor += 1
        return text

    def peek(self) -> _Line | None:
        """The next significant line, without consuming it."""
        while self.pos < len(self.lines):
            raw = self.lines[self.pos]
            stripped = self.strip_comment(raw).rstrip()
            if not stripped.strip():
                self.pos += 1
                continue
            indent = len(stripped) - len(stripped.lstrip(" "))
            if "\t" in stripped[: len(stripped) - len(stripped.lstrip())]:
                self.fail(self.pos, "tabs cannot indent YAML; re-indent with spaces")
            return _Line(self.pos, indent, stripped[indent:])
        return None

    def load(self) -> Any:
        first = self.peek()
        if first is None:
            self.fail(0, "the document is empty")
        if first.text.startswith("%"):
            self.fail(first.index, "YAML directives are not supported")
        if first.text == "---":
            self.pos += 1
        value = self.parse_block(0)
        trailing = self.peek()
        if trailing is not None and trailing.text not in {"...", "---"}:
            self.fail(trailing.index, f"unexpected content after the document: {trailing.text!r}")
        if trailing is not None and trailing.text == "---":
            self.fail(
                trailing.index,
                "the file holds more than one YAML document; an OpenAPI source is one document",
            )
        return value

    def parse_block(self, min_indent: int) -> Any:
        """Parse the block starting at the next significant line."""
        line = self.peek()
        if line is None or line.indent < min_indent:
            return None
        if line.text == "-" or line.text.startswith("- "):
            return self.parse_sequence(line.indent)
        if line.text == "?" or line.text.startswith("? "):
            self.fail(line.index, "explicit `? ` mapping keys are not supported")
        if line.text == ":" or line.text.startswith(": "):
            self.fail(line.index, "an empty mapping key is not supported")
        if self.split_key(line.text) is None:
            # Not an entry: a scalar written on its own line(s) under its key, the
            # way real documents wrap a long `description:`.
            self.pos = line.index + 1
            return self.parse_value(line.text, line.indent - 1, line.index)
        return self.parse_mapping(line.indent)

    def parse_mapping(self, indent: int) -> dict[Any, Any]:
        mapping: dict[Any, Any] = {}
        merges: list[Any] = []
        while True:
            line = self.peek()
            if line is None or line.indent < indent:
                break
            if line.indent == 0 and line.text in {"---", "..."}:
                break  # a document marker ends this block; load() reports it
            if line.indent > indent:
                self.fail(line.index, "unexpected indentation inside a block mapping")
            if line.text == "-" or line.text.startswith("- "):
                self.fail(line.index, "a sequence item where a mapping key was expected")
            if line.text == ":" or line.text.startswith(": "):
                self.fail(line.index, "an empty mapping key is not supported")
            split = self.split_key(line.text)
            if split is None:
                self.fail(line.index, f"expected a `key: value` mapping entry, got {line.text!r}")
            key_text, rest = split
            key = self.parse_key(line, key_text)
            self.pos = line.index + 1
            value = self.parse_value(rest, indent, line.index)
            if key == "<<":
                merges.append(value)
            else:
                mapping[key] = value
        for merged in merges:
            for source in merged if isinstance(merged, list) else [merged]:
                if isinstance(source, dict):
                    for key, value in source.items():
                        mapping.setdefault(key, value)
        return mapping

    def parse_sequence(self, indent: int) -> list[Any]:
        items: list[Any] = []
        while True:
            line = self.peek()
            if line is None or line.indent < indent:
                break
            if line.indent == 0 and line.text in {"---", "..."}:
                break  # a document marker ends this block; load() reports it
            if line.indent > indent:
                self.fail(line.index, "unexpected indentation inside a block sequence")
            if not (line.text == "-" or line.text.startswith("- ")):
                break
            rest = line.text[1:].lstrip(" ")
            if rest == "":
                self.pos = line.index + 1
                items.append(self.parse_block(indent + 1))
                continue
            if rest.startswith("- ") or rest == "-" or self.split_key(rest) is not None:
                # A nested collection opening on the dash line: blank the dash so
                # the item's own lines all sit at one indentation, then parse it
                # as an ordinary block. Rewriting the line (rather than threading
                # a synthetic first line through the parser) keeps every later
                # line of the item on its real source index, so failures still
                # name the line the reader would look at.
                raw = self.lines[line.index]
                self.lines[line.index] = raw[: line.indent] + " " + raw[line.indent + 1 :]
                items.append(self.parse_block(indent + 1))
                continue
            self.pos = line.index + 1
            items.append(self.parse_value(rest, indent, line.index))
        return items

    def split_key(self, text: str) -> tuple[str, str] | None:
        """Split `key: value` into its halves, or None when `text` is not an entry."""
        if text[0] in "\"'":
            end = self.scan_quoted(text, 0)
            if end is None or not (text[end:] == ":" or text[end:].startswith(": ")):
                return None
            return text[:end], text[end + 1 :].lstrip(" ")
        if text.startswith(("[", "{", "&", "*", "|", ">")):
            return None
        match = _KEY_END.search(text)
        if match is None or not text[: match.start()].strip():
            return None  # no `key:` at all, or the empty key `: value`
        return text[: match.start()], text[match.end() :].lstrip(" ")

    def parse_key(self, line: _Line, key_text: str) -> Any:
        if key_text.startswith("? "):
            self.fail(line.index, "explicit `? ` mapping keys are not supported")
        if key_text.startswith("!"):
            self.fail(line.index, "YAML tags are not supported")
        if key_text[0] in "\"'":
            end = self.scan_quoted(key_text, 0)
            assert end is not None  # split_key only returns a terminated quote
            return self.unquote(line, key_text[:end])
        return self.scalar(key_text.rstrip())

    def parse_value(self, rest: str, indent: int, index: int) -> Any:
        """The value of a mapping entry or sequence item declared on line `index`."""
        anchor = None
        if rest.startswith("&"):
            name, _, remainder = rest.partition(" ")
            anchor = name[1:]
            rest = remainder.lstrip(" ")
        if rest.startswith("!"):
            self.fail(index, "YAML tags are not supported")
        if rest.startswith("*"):
            name = rest[1:].strip()
            if name not in self.anchors:
                self.fail(index, f"alias *{name} has no anchor")
            value: Any = self.anchors[name]
        elif rest == "":
            following = self.peek()
            # A block sequence may sit at its key's own indentation, and most
            # generator-written documents do exactly that; anything else has to be
            # more indented than the key to belong to it.
            nested = following is not None and (
                following.indent > indent
                or (
                    following.indent == indent
                    and (following.text == "-" or following.text.startswith("- "))
                )
            )
            value = self.parse_block(following.indent) if nested else None
        elif rest[0] in "|>":
            value = self.block_scalar(rest, indent, index)
        elif rest[0] in "[{":
            value = self.flow(rest, index)
        else:
            value = self.scalar_value(rest, indent, index)
        if anchor is not None:
            self.anchors[anchor] = value
        return value

    def block_scalar(self, header: str, indent: int, index: int) -> str:
        style, header = header[0], header[1:].strip()
        chomp = ""
        explicit = 0
        for char in header:
            if char in "+-":
                chomp = char
            elif char.isdigit():
                explicit = int(char)
            else:
                self.fail(index, f"unsupported block scalar header {header!r}")
        body: list[str] = []
        block_indent = indent + explicit if explicit else 0
        cursor = index + 1
        while cursor < len(self.lines):
            raw = self.lines[cursor]
            if raw.strip() == "":
                body.append("")
                cursor += 1
                continue
            line_indent = len(raw) - len(raw.lstrip(" "))
            if line_indent <= indent:
                break
            if not block_indent:
                block_indent = line_indent
            if line_indent < block_indent:
                break
            body.append(raw[block_indent:])
            cursor += 1
        self.pos = cursor
        trailing = 0
        while body and body[-1] == "":
            body.pop()
            trailing += 1
        text = "\n".join(body) if style == "|" else self.fold(body)
        if chomp == "-" or not text:
            return text
        return text + "\n" * (1 + trailing if chomp == "+" else 1)

    @staticmethod
    def fold(body: list[str]) -> str:
        """Fold a `>` scalar: a break between two lines becomes a space, a run of
        empty lines becomes that many breaks, and a more-indented line keeps its
        own breaks."""
        out: list[str] = []
        folding = False
        cursor = 0
        while cursor < len(body):
            entry = body[cursor]
            if entry == "":
                run = 0
                while cursor < len(body) and body[cursor] == "":
                    run += 1
                    cursor += 1
                out.append("\n" * run)
                folding = False
                continue
            if entry.startswith(" "):
                out.append(("\n" if folding else "") + entry)
                folding = False
            else:
                out.append((" " if folding else "") + entry)
                folding = True
            cursor += 1
        return "".join(out)

    def scalar_value(self, rest: str, indent: int, index: int) -> Any:
        """A quoted or plain scalar, folding any more-indented continuation lines."""
        if rest[0] in "\"'":
            end = self.scan_quoted(rest, 0)
            if end is not None:
                trailing = rest[end:].strip()
                if trailing:
                    self.fail(index, f"unexpected text after a quoted scalar: {trailing!r}")
                return self.unquote(self.line_at(index), rest[:end])
            return self.multiline_quoted(rest, indent, index)
        pieces = [rest]
        cursor = index + 1
        while cursor < len(self.lines):
            candidate = self.strip_comment(self.lines[cursor]).rstrip()
            if not candidate.strip():
                break
            candidate_indent = len(candidate) - len(candidate.lstrip(" "))
            if candidate_indent <= indent:
                break
            pieces.append(candidate.strip())
            cursor += 1
        self.pos = cursor
        if len(pieces) == 1:
            return self.scalar(rest.strip())
        return " ".join(pieces)

    def multiline_quoted(self, rest: str, indent: int, index: int) -> str:
        """A quoted scalar whose closing quote is on a later line.

        The source line breaks are folded away BEFORE the escapes are read, which
        is the only order that survives a document like slurmdb-rest's: a
        double-quoted description holding both real `\\n` escapes and a trailing
        `\\` that cancels the source break. Folding afterwards would eat the
        escapes along with the breaks.
        """
        quote = rest[0]
        buffer = rest.rstrip()
        blanks = 0
        cursor = index + 1
        while cursor < len(self.lines):
            piece = self.lines[cursor].strip()
            cursor += 1
            if not piece:
                blanks += 1
                continue
            if quote == '"' and (len(buffer) - len(buffer.rstrip("\\"))) % 2 == 1:
                buffer = buffer[:-1] + piece  # a trailing backslash cancels the break
            elif blanks:
                buffer = f"{buffer}{chr(10) * blanks}{piece}"
            else:
                buffer = f"{buffer} {piece}"
            blanks = 0
            end = self.scan_quoted(buffer, 0)
            if end is not None:
                trailing = buffer[end:].strip()
                if trailing:
                    self.fail(index, f"unexpected text after a quoted scalar: {trailing!r}")
                self.pos = cursor
                return self.unquote(self.line_at(index), buffer[:end])
        self.fail(index, "a quoted scalar is never closed")
        raise AssertionError("unreachable")  # pragma: no cover - fail() raises

    def line_at(self, index: int) -> _Line:
        raw = self.strip_comment(self.lines[index]).rstrip()
        indent = len(raw) - len(raw.lstrip(" "))
        return _Line(index, indent, raw[indent:])

    @staticmethod
    def scan_quoted(text: str, start: int) -> int | None:
        """The index just past the quoted scalar at `start`, or None if unterminated."""
        quote = text[start]
        cursor = start + 1
        while cursor < len(text):
            char = text[cursor]
            if quote == '"' and char == "\\":
                cursor += 2
                continue
            if char == quote:
                if quote == "'" and text[cursor + 1 : cursor + 2] == "'":
                    cursor += 2
                    continue
                return cursor + 1
            cursor += 1
        return None

    def unquote(self, line: _Line, text: str) -> str:
        if text[0] == "'":
            return text[1:-1].replace("''", "'")
        body = text[1:-1]
        out: list[str] = []
        cursor = 0
        while cursor < len(body):
            char = body[cursor]
            if char != "\\":
                out.append(char)
                cursor += 1
                continue
            marker = body[cursor + 1 : cursor + 2]
            if marker in ("x", "u", "U"):
                width = {"x": 2, "u": 4, "U": 8}[marker]
                digits = body[cursor + 2 : cursor + 2 + width]
                try:
                    out.append(chr(int(digits, 16)))
                except ValueError:
                    self.fail(line.index, f"invalid \\{marker} escape {digits!r}")
                cursor += 2 + width
                continue
            if marker == "\n":
                cursor += 2
                continue
            if marker not in _ESCAPES:
                self.fail(line.index, f"unsupported escape \\{marker}")
            out.append(_ESCAPES[marker])
            cursor += 2
        return "".join(out)

    def flow(self, rest: str, index: int) -> Any:
        """A flow collection, gathered across lines until its brackets balance."""
        buffer = rest
        cursor = index + 1
        while self.flow_depth(buffer) > 0 and cursor < len(self.lines):
            buffer = f"{buffer} {self.strip_comment(self.lines[cursor]).strip()}"
            cursor += 1
        if self.flow_depth(buffer) != 0:
            self.fail(index, "a flow collection is never closed")
        self.pos = cursor
        value, end = self.flow_node(buffer, 0, index)
        if buffer[end:].strip():
            self.fail(index, f"unexpected text after a flow collection: {buffer[end:].strip()!r}")
        return value

    def flow_depth(self, text: str) -> int:
        depth = 0
        cursor = 0
        while cursor < len(text):
            char = text[cursor]
            if char in "\"'":
                end = self.scan_quoted(text, cursor)
                cursor = end if end is not None else len(text)
                continue
            if char in "[{":
                depth += 1
            elif char in "]}":
                depth -= 1
            cursor += 1
        return depth

    def flow_node(self, text: str, start: int, index: int) -> tuple[Any, int]:
        cursor = self.skip_space(text, start)
        if cursor >= len(text):
            self.fail(index, "a flow collection ends where a value was expected")
        char = text[cursor]
        if char == "[":
            return self.flow_collection(text, cursor, index, "]")
        if char == "{":
            return self.flow_collection(text, cursor, index, "}")
        if char in "\"'":
            end = self.scan_quoted(text, cursor)
            if end is None:
                self.fail(index, "a quoted scalar in a flow collection is never closed")
            return self.unquote(self.line_at(index), text[cursor:end]), end
        end = cursor
        while end < len(text) and text[end] not in ",]}:":
            end += 1
        raw = text[cursor:end].strip()
        if raw.startswith("*"):
            name = raw[1:]
            if name not in self.anchors:
                self.fail(index, f"alias *{name} has no anchor")
            return self.anchors[name], end
        return self.scalar(raw), end

    def flow_collection(self, text: str, start: int, index: int, closer: str) -> tuple[Any, int]:
        items: list[Any] = []
        mapping: dict[Any, Any] = {}
        cursor = start + 1
        while True:
            entered = cursor
            cursor = self.skip_space(text, cursor)
            if cursor >= len(text):
                self.fail(index, "a flow collection is never closed")
            if text[cursor] == closer:
                return (mapping if closer == "}" else items), cursor + 1
            value, cursor = self.flow_node(text, cursor, index)
            cursor = self.skip_space(text, cursor)
            if cursor < len(text) and text[cursor] == ":":
                entry, cursor = self.flow_node(text, cursor + 1, index)
                mapping[value] = entry
            else:
                items.append(value)
            cursor = self.skip_space(text, cursor)
            if cursor < len(text) and text[cursor] == ",":
                cursor += 1
            if cursor <= entered:
                # `flow_node` stops at `,]}:` and so returns without consuming a
                # delimiter it does not recognise here. Looping again from the
                # same cursor would append forever and exhaust memory rather than
                # report anything, so a round that consumed nothing is a parse
                # error naming where it stalled.
                self.fail(index, f"a flow collection stalls at {text[cursor:cursor + 1]!r}")

    @staticmethod
    def skip_space(text: str, cursor: int) -> int:
        while cursor < len(text) and text[cursor] in " \t":
            cursor += 1
        return cursor

    @staticmethod
    def scalar(text: str) -> Any:
        """Resolve a plain scalar to the type YAML's core schema gives it."""
        if text in _NULL:
            return None
        if text in _TRUE:
            return True
        if text in _FALSE:
            return False
        if _INT.match(text):
            return int(text)
        if _FLOAT.match(text) or _EXP.match(text):
            return float(text)
        return text


def load_document(path: Path) -> Any:
    """Parse one OpenAPI source document into plain Python objects."""
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as error:
        raise DocumentError(path, 0, f"cannot be read: {error}") from error
    if text.startswith("﻿"):
        text = text[1:]
    if path.suffix == ".json":
        try:
            return json.loads(text)
        except json.JSONDecodeError as error:
            raise DocumentError(path, error.lineno, f"is not valid JSON: {error.msg}") from error
    return _YamlReader(path, text).load()


