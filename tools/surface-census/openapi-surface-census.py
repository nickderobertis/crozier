def string_enum_values(node: Any) -> list[str] | None:
    """`string_enum_values` of `src/ir.rs`: the strings it yields, or `None`.

    The `enum` array if one is written, else the one-member array its `const`
    falls back to, filtered to strings under the same three conditions
    `string_valued` above already ports — which is why this calls it rather than
    restating them.
    """
    if not isinstance(node, dict):
        return None
    if written(node, "enum"):
        values = node["enum"]
        if not isinstance(values, list):
            return None
    elif written(node, "const"):
        values = [node["const"]]
    else:
        return None
    if not string_valued(node, values):
        return None
    return [value for value in values if isinstance(value, str)]


def schema_example(node: dict[Any, Any]) -> Any:
    """`schema_example` after `de_schema_examples` of `src/openapi.rs`."""
    # serde's Option<Value> treats an explicit JSON null as None; the vector of
    # `examples` does not, so a null first member there is still selected.
    if written(node, "example") and node["example"] is not None:
        return node["example"]
    examples = node.get("examples")
    if isinstance(examples, list) and examples:
        return examples[0]
    if isinstance(examples, dict) and examples:
        first = next(iter(examples.values()))
        return first.get("value") if isinstance(first, dict) else first
    if examples is not None and not isinstance(examples, (list, dict)):
        return examples
    return None


def selected_example_kind(node: dict[Any, Any]) -> str | None:
    """The six JSON arms read by emit.rs, after ir.rs's example selection."""
    examples = node.get("examples")
    has_examples = bool(examples) if isinstance(examples, (list, dict)) else examples is not None
    if node.get("example") is None and not has_examples:
        return None
    value = schema_example(node)
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "boolean"
    if isinstance(value, dict):
        return "object"
    if isinstance(value, list):
        return "array"
    if isinstance(value, (int, float)):
        return "number"
    if isinstance(value, str):
        return "string"
    return None


# The `enum_identifier` trace entries that are a `schema.enum:<entry>-member`
# predicate of their own.
_TRACED_ENUM_BRANCHES = frozenset(
    {
        "deburred",
        "letter-run",
        "alphanumeric-join",
        "digit-boundary",
        "single-digit-prefix",
        "numeric-small",
        "numeric-tens",
        "numeric-hundreds",
        "numeric-thousands",
    }
)


def enum_member_predicates(node: dict[Any, Any]) -> list[str]:
    """Count the member spellings that naming.rs branches on, once per schema."""
    values = node.get("enum")
    if not isinstance(values, list):
        return []
    found: set[str] = set()
    names: dict[str, int] = defaultdict(int)
    for value in values:
        if isinstance(value, (int, float)) and not isinstance(value, bool):
            found.add("schema.enum:numeric-member")
            continue
        if not isinstance(value, str):
            continue
        if value == "":
            found.add("schema.enum:empty-member")
        if "*" in value:
            found.add("schema.enum:wildcard-member")
        if "'" in value or "\u2019" in value:
            found.add("schema.enum:apostrophe-member")
        words = split_words(re.sub(r"[^A-Za-z0-9]", " ", value))
        prefix = re.match(r"[0-9]+", value)
        if prefix and 1 < len(prefix.group()) <= 4 and prefix.group()[0] != "0":
            found.add("schema.enum:numeric-prefix-member")
        if any(len(word) > 1 and word[0] == "0" and word.isdigit() for word in words):
            found.add("schema.enum:leading-zero-member")
        parts = value.split("-")
        if len(parts) == 5 and all(
            len(part) == size and all(char in "0123456789abcdefABCDEF" for char in part)
            for part, size in zip(parts, (8, 4, 4, 4, 12), strict=False)
        ):
            found.add("schema.enum:uuid-member")
            first = split_words(value)[0]
            if len(first) > 1 and first[0].isdigit() and not first[1].isdigit():
                found.add("schema.enum:digit-word-member")
        trace: set[str] = set()
        name = enum_identifier(value, trace)
        found.update(f"schema.enum:{branch}-member" for branch in trace & _TRACED_ENUM_BRANCHES)
        if value and not name:
            found.add("schema.enum:empty-identifier-member")
        if name and name[0].isdigit():
            found.add("schema.enum:leading-digit-identifier")
        if is_reserved(name):
            found.add("schema.enum:reserved-member")
        names[name.upper()] += 1
    if any(count > 1 for count in names.values()):
        found.add("schema.enum:normalized-collision")
    return sorted(found)


def _is_integer(value: Any) -> bool:
    return isinstance(value, int) and not isinstance(value, bool)


def example_content_predicates(node: dict[Any, Any]) -> list[str]:
    """The example predicates read off one Schema Object's own fields.

    Each asks what `value_from_example` and `example_matches_type` of
    `src/emit.rs` would branch on for this node's selected example, read through
    the type its own fields give it, which is all a node-local reading can see.
    """
    if selected_example_kind(node) is None:
        return []
    example = schema_example(node)
    found: list[str] = []
    fmt = node.get("format")
    if isinstance(example, str) and fmt == "date-time":
        found.append("schema.example:date-time-string")
    if isinstance(example, str) and fmt == "date":
        found.append("schema.example:date-string")
    primary = primary_type(node.get("type"))
    if primary == "number" and _is_integer(example):
        found.append("schema.example:integral-on-number")
    if primary == "integer" and isinstance(example, float):
        found.append("schema.example:fractional-on-integer")
    if example == [] and isinstance(example, list):
        found.append("schema.example:empty-array")
    if example == {} and isinstance(example, dict):
        found.append("schema.example:empty-object")
    if isinstance(example, list):
        if any(element is None for element in example):
            found.append("schema.example:array-null-element")
        if any(isinstance(element, dict) for element in example):
            found.append("schema.example:array-object-element")
        items = node.get("items")
        if (
            isinstance(items, dict)
            and items.get("format") in {"date", "date-time"}
            and any(element == other for index, element in enumerate(example) for other in example[:index])
        ):
            found.append("schema.example:temporal-duplicate-element")
    if (
        isinstance(example, dict)
        and list(example) == ["$ref"]
        and any(isinstance(node.get(field), list) for field in ("oneOf", "anyOf"))
    ):
        found.append("schema.example:union-ref-sentinel")
    properties = node.get("properties")
    if isinstance(example, dict) and isinstance(properties, dict) and properties:
        required = node.get("required")
        required = required if isinstance(required, list) else []
        if any(name in properties and name not in example for name in required):
            found.append("schema.example:missing-required-field")
        if any(key not in properties for key in example):
            found.append("schema.example:undeclared-field")
    if isinstance(example, dict):
        values = list(example.values())
        if any(isinstance(value, dict) and not value for value in values):
            found.append("schema.example:empty-object-member")
        if any(isinstance(value, list) and not value for value in values):
            found.append("schema.example:empty-array-member")
        additional = node.get("additionalProperties")
        if (additional is True or isinstance(additional, dict)) and not (isinstance(properties, dict) and properties):
            found.append("schema.example:object-on-map")
    members = string_enum_values(node) if "enum" in node else None
    if isinstance(example, str) and members is not None and example not in members:
        found.append("schema.example:outside-enum")
    return found


def optional_property_example(node: dict[Any, Any]) -> bool:
    """`schema.properties:optional-example`: a property `required` omits selects an example."""
    properties = node.get("properties")
    if not isinstance(properties, dict):
        return False
    required = node.get("required")
    required = set(required) if isinstance(required, list) else set()
    return any(
        name not in required and isinstance(value, dict) and selected_example_kind(value) is not None
        for name, value in properties.items()
    )


def named_target_kind(target: Any) -> str | None:
    """What a resolved component declares, as the four named-declaration arms read it."""
    if not isinstance(target, dict):
        return None
    if any(isinstance(target.get(field), list) for field in ("oneOf", "anyOf")):
        return "union"
    if "enum" in target and string_valued(target, target.get("enum")):
        return "enum"
    properties = target.get("properties")
    if isinstance(properties, dict) and properties:
        return "object"
    if "allOf" in target:
        return None
    return "alias"


def example_is_schema_definition(example: Any) -> bool:
    """The content test `src/ir.rs`'s `example_is_schema_definition` made.

    That helper went with the `hoist_union_variant` arm that called it, once Fern
    was shown to map every bare object member whatever its example; this reading
    still backs `schema.example:schema-shaped`, which the
    `oneof-bare-object-example-variant` row's selector composes, and
    `test_the_schema_shaped_reading_keeps_the_removed_helpers_truth_table` pins
    it to that helper's own unit-test table.
    """
    if not isinstance(example, dict) or not example:
        return False
    schema_keys = {"type", "$ref", "properties", "allOf", "oneOf", "anyOf"}
    return all(isinstance(value, dict) and bool(schema_keys & value.keys()) for value in example.values())


def discriminant_value(node: Any) -> str | None:
    """`discriminant_value` of `src/ir.rs`: the tag one member writes, or `None`.

    Two spellings and no others: a **one-member** string `enum` (or the `const`
    that stands in for one), or a string `example`. An `enum` of two strings is
    not a tag, and neither is a numeric one.
    """
    if not isinstance(node, dict):
        return None
    values = string_enum_values(node)
    if values is not None and len(values) == 1:
        return values[0]
    example = schema_example(node)
    return example if isinstance(example, str) else None


def union_members(node: dict[Any, Any]) -> list[Any] | None:
    """`one_of.as_ref().or(any_of.as_ref())` of `src/ir.rs`, over a raw node.

    `oneOf` wins wherever both are written, exactly as the `or` has it. A field
    written as something other than an array is a document crozier refuses at the
    boundary, and reads as no union here.
    """
    for field in ("oneOf", "anyOf"):
        if written(node, field):
            members = node[field]
            return members if isinstance(members, list) else None
    return None


# The values `inferred_discriminant_property_with` refuses to read as a
# `message_type` tag, which is `preserve_const_discriminant` of `src/ir.rs` and is
# its list rather than one invented here. The four property names that same
# function supports for a union referencing components are spelled in the `match`
# `_candidate_tag_values` mirrors below, where the Rust spells them, because each
# of the four asks something different of the member.
_PRESERVED_CONST_DISCRIMINANTS = frozenset(
    {
        "approval",
        "approval_request_message",
        "message",
        "tool",
        "tool_return_message",
        "stop_reason",
        "usage_statistics",
    }
)


def _resolved_member(member: Any, schemas: dict[Any, Any]) -> Any:
    """One union member as the *resolving* readers of it see it.

    `resolve_ref_from_schemas` is the last-segment lookup the `~>` operator
    already mirrors. `inferred_discriminant_property_with` falls back to the
    member itself where the lookup finds nothing (`unwrap_or(variant)`); the
    member loop of `discriminated_union` does not, and calls
    `_resolved_member_strict` instead.
    """
    if not isinstance(member, dict):
        return member
    reference = member.get("$ref")
    if not isinstance(reference, str):
        return member
    target = schemas.get(reference.rsplit("/")[-1])
    return target if isinstance(target, dict) else member


def _resolved_member_strict(member: Any, schemas: dict[Any, Any]) -> dict[Any, Any] | None:
    """One union member resolved, or `None` where `resolve_ref_from_schemas` fails."""
    if not isinstance(member, dict):
        return None
    reference = member.get("$ref")
    if not isinstance(reference, str):
        return member
    target = schemas.get(reference.rsplit("/")[-1])
    return target if isinstance(target, dict) else None


def _inferred_discriminant_property(node: dict[Any, Any], schemas: dict[Any, Any], enum_tag: bool = True) -> str | None:
    """`inferred_discriminant_property_with` of `src/ir.rs`, condition for condition.

    The first resolved member's property *names* are the candidates, in the order
    it declares them, and a candidate wins when every resolved member carries a
    readable tag for it and the tags are all distinct. What "readable" means
    depends on whether the union references components at all: where it does, a
    member either tags itself with a required one-member `enum` or the property is
    one of the four `src/ir.rs` supports by name, or every member is a `$ref`
    whose tag `required` leaves out; where it does not, a one-member `enum` is
    required of every member.
    """
    members = union_members(node)
    if members is None:
        return None
    references_components = any(isinstance(member, dict) and isinstance(member.get("$ref"), str) for member in members)
    only_references = all(isinstance(member, dict) and isinstance(member.get("$ref"), str) for member in members)
    resolved = [_resolved_member(member, schemas) for member in members]
    if not resolved or not isinstance(resolved[0], dict):
        return None
    first_properties = resolved[0].get("properties")
    if not isinstance(first_properties, dict):
        return None
    for candidate in first_properties:
        if not isinstance(candidate, str):
            continue
        values = _candidate_tag_values(
            candidate,
            resolved,
            references_components,
            enum_tag,
            _any_of_head(node),
            only_references,
        )
        if values is not None and len(set(values)) == len(values):
            return candidate
    return None


def _candidate_tag_values(
    candidate: str,
    resolved: list[Any],
    references_components: bool,
    enum_tag: bool,
    any_of_head: bool = False,
    only_references: bool = False,
) -> list[str] | None:
    """The tag every resolved member writes for one candidate property, or `None`.

    One iteration of the `find_map` closure above: the `collect::<Option<Vec<_>>>`
    fails as soon as one member declares no readable tag, which is what a `None`
    here says.
    """
    values: list[str] = []
    for variant in resolved:
        if not isinstance(variant, dict):
            return None
        properties = variant.get("properties")
        field = properties.get(candidate) if isinstance(properties, dict) else None
        if not isinstance(field, dict):
            return None
        enum_written = field["enum"] if written(field, "enum") else None
        singleton_enum = not (any_of_head and untyped_enum_tag(field)) and len(string_enum_values(field) or []) == 1
        tagged_by_enum = (
            candidate in required_names(variant)
            and singleton_enum
            and isinstance(enum_written, list)
            and len(enum_written) == 1
        )
        if references_components and not (enum_tag and tagged_by_enum):
            # Members that are all `$ref`s tagging the property with one string
            # `required` leaves out: the `unrequired_tag` clause, whatever the name.
            if only_references and singleton_enum and candidate not in required_names(variant):
                supported = True
            elif candidate == "type":
                supported = (candidate in required_names(variant) and isinstance(schema_example(field), str)) or (
                    written(field, "const") and isinstance(field["const"], str)
                )
            elif candidate in ("role", "status"):
                supported = candidate in required_names(variant)
            elif candidate in ("message_type", "mcp_server_type"):
                supported = True
            elif candidate == "name":
                supported = singleton_enum
            else:
                supported = (
                    candidate in required_names(variant) and written(field, "const") and isinstance(field["const"], str)
                )
            if not supported:
                return None
        elif not singleton_enum:
            return None
        value = discriminant_value(field)
        if value is None:
            return None
        if candidate == "message_type" and value in _PRESERVED_CONST_DISCRIMINANTS:
            return None
        values.append(value)
    return values


def _inferred_union_discriminant_property(node: dict[Any, Any], schemas: dict[Any, Any]) -> str | None:
    """`inferred_union_discriminant_property` of `src/ir.rs`, with its fallback.

    The fallback reads `type` off every resolved member that requires it, and
    accepts either tag spelling `discriminant_value` reads. A union with no
    members at all satisfies it vacuously — nought distinct values out of nought —
    which is how an empty `oneOf: []` reaches `discriminated_union`'s `Some`.
    """
    found = _inferred_discriminant_property(node, schemas, True)
    if found is not None:
        return found
    members = union_members(node)
    if members is None:
        return None
    values: list[str] = []
    for member in members:
        variant = _resolved_member(member, schemas)
        if not isinstance(variant, dict) or "type" not in required_names(variant):
            return None
        properties = variant.get("properties")
        field = properties.get("type") if isinstance(properties, dict) else None
        if _any_of_head(node) and untyped_enum_tag(field):
            return None
        value = discriminant_value(field)
        if value is None:
            return None
        values.append(value)
    return "type" if len(set(values)) == len(values) else None


def _any_of_head(node: dict[Any, Any]) -> bool:
    """Whether a union's members are its `anyOf`: one is written and no `oneOf` is."""
    return written(node, "anyOf") and not written(node, "oneOf")


def untyped_enum_tag(field: Any) -> bool:
    """`untyped_any_of_enum_tag` of `src/ir.rs`, given an `anyOf` head: an `enum`
    tag declaring no `type: string`, which Fern does not discriminate on."""
    return isinstance(field, dict) and written(field, "enum") and primary_type(field.get("type")) != "string"


def _mapping_targets_resolve(mapping: dict[Any, Any], schemas: dict[Any, Any]) -> bool:
    """`self.schemas.get(target_key)?`, over every entry of a written `mapping`."""
    for reference in mapping.values():
        if not isinstance(reference, str):
            return False
        if not isinstance(schemas.get(reference.rsplit("/")[-1]), dict):
            return False
    return True


def _written_discriminator(node: dict[Any, Any]) -> dict[Any, Any] | None:
    """The Discriminator Object this schema writes, as `Option<Discriminator>`."""
    discriminator = node.get("discriminator")
    return discriminator if isinstance(discriminator, dict) else None


def inheritance_union(node: dict[Any, Any], schemas: dict[Any, Any]) -> bool:
    """`inheritance_discriminated_union` of `src/ir.rs` returning `Some`.

    OpenAPI's other polymorphism spelling: a base object whose `discriminator`
    names its subtypes through a `mapping`, with no `oneOf` or `anyOf` of its own.
    Its three conditions are a `discriminator`, a non-empty `propertyName`, and a
    non-empty `mapping` every entry of which resolves.

    **One reading rather than a port.** The Rust lets a mapping entry naming the
    union's *own* coined class name through without resolving it — the wrapper
    holds the alias in a `value` field — and that name is coined from the call
    site rather than declared by the document, so no census can decide it. This
    requires every entry to resolve. The two disagree only on a mapping naming a
    component this document does not declare whose class name is nonetheless the
    one the caller would coin, which is a document contradicting itself; the case
    analysis records the divergence beside the case.
    """
    discriminator = _written_discriminator(node)
    if discriminator is None:
        return False
    property_name = discriminator.get("propertyName")
    if not isinstance(property_name, str) or not property_name:
        return False
    mapping = discriminator.get("mapping")
    if not isinstance(mapping, dict) or not mapping:
        return False
    return _mapping_targets_resolve(mapping, schemas)


def discriminated_union_head(node: dict[Any, Any], schemas: dict[Any, Any]) -> str | None:
    """Which composition head `discriminated_union` builds this union from, if any.

    `discriminated_union` of `src/ir.rs`, arm for arm, answering `"oneOf"`,
    `"anyOf"` or `None`:

    * a schema declaring neither is not this shape at all — it is the inheritance
      spelling, which `inheritance_union` above decides;
    * a `discriminator` written beside an `anyOf` with no `oneOf` is **ignored**,
      because Fern applies an explicit discriminator to `oneOf` alone: the union
      is read as though none were written;
    * the discriminant property is the written `propertyName` where one is
      non-empty, and the *inferred* property otherwise — so a union carrying no
      `discriminator` at all reaches this;
    * where no non-empty `mapping` is written, every member — resolved first, if
      it is a `$ref` — must carry a `discriminant_value` for that property;
    * where one is, every mapping target must resolve.
    """
    if not written(node, "oneOf") and not written(node, "anyOf"):
        return None
    discriminator = _written_discriminator(node)
    if discriminator is not None and not written(node, "oneOf"):
        return discriminated_union_head({key: value for key, value in node.items() if key != "discriminator"}, schemas)
    members = union_members(node)
    if members is None:
        return None
    property_name = None
    if discriminator is not None:
        declared = discriminator.get("propertyName")
        if isinstance(declared, str) and declared:
            property_name = declared
    if property_name is None:
        property_name = _inferred_union_discriminant_property(node, schemas)
    if property_name is None:
        return None
    mapping = discriminator.get("mapping") if discriminator is not None else None
    if isinstance(mapping, dict) and mapping:
        if not _mapping_targets_resolve(mapping, schemas):
            return None
    else:
        for member in members:
            target = _resolved_member_strict(member, schemas)
            if target is None:
                return None
            properties = target.get("properties")
            field = properties.get(property_name) if isinstance(properties, dict) else None
            if discriminant_value(field) is None:
                return None
    return "oneOf" if written(node, "oneOf") else "anyOf"


def components_schemas(document: Any) -> dict[Any, Any]:
    """One document's own `components.schemas` map, as the census reads it.

    The document being censused and nothing else: a `$ref` naming another document
    is a string to this instrument, never a fetch and never a second document.
    """
    if not isinstance(document, dict):
        return {}
    components = document.get("components")
    if not isinstance(components, dict):
        return {}
    schemas = components.get("schemas")
    return schemas if isinstance(schemas, dict) else {}


def grammar() -> tuple[set[str], set[str]]:
    """Every selector the grammar allows, and every prefix that can carry an `x-`.

    Enumerable because a selector is an anchor kind's name followed by a chain of
    fields through *extending* kinds only — the chain stops at the next anchor,
    which starts a selector of its own. That closed set is what makes a mistyped
    `--selector` refusable instead of silently reportable as undeclared.
    """
    selectors: set[str] = set()
    prefixes: set[str] = set()

    def visit(kind_name: str, prefix: str) -> None:
        if prefix in prefixes:
            return
        prefixes.add(prefix)
        kind = OBJECTS[kind_name]
        for field, child in kind.fields.items():
            selectors.add(f"{prefix}.{field}")
            if child is not None and not OBJECTS[child.kind].anchor:
                visit(child.kind, f"{prefix}.{field}")
        if kind.free_map is not None and not OBJECTS[kind.free_map.kind].anchor:
            visit(kind.free_map.kind, prefix)

    for name, kind in OBJECTS.items():
        if kind.anchor:
            visit(name, kind.name)
    return selectors, prefixes


def selector_error(text: str) -> str | None:
    """Why this `--selector` names nothing the grammar can emit, or None."""
    selectors, prefixes = grammar()
    if NEGATION in text:
        # A negated spelling is refused for what is wrong with it — an unanchored
        # complement, or a descent bound to a member the node does not write —
        # rather than reported as a shape nobody declares.
        malformed = conjunction_error(text)
        if malformed is not None:
            return malformed
    if is_conjunction(text) or NEGATION in text:
        # The conjunction list is closed by the branch structure of the six blind
        # functions, not by what the operators can spell, so a well-formed
        # combination nobody declared is refused exactly as a typo is.
        if text in CONJUNCTIONS:
            return None
        close = difflib.get_close_matches(text, sorted(CONJUNCTIONS), n=3)
        suggestion = f" Did you mean: {', '.join(close)}?" if close else ""
        return (
            f"{text!r} is not one of the conjunction selectors the census declares."
            f"{suggestion} The closed list of {len(CONJUNCTIONS)} is declared in "
            "tools/surface-census/openapi-surface-census.py and restated in "
            "docs/openapi-surface-coverage.md."
        )
    base, equals, value = text.partition("=")
    if ":" in base:
        # A predicate first, even when the spelling carries an `=`: the family
        # reads a member's *position* as well as its presence, so
        # `schema.type:primary=array` is one predicate's name rather than a valued
        # selector over a field called `schema.type:primary`.
        if text in PREDICATES:
            return None
        close = difflib.get_close_matches(text, sorted(PREDICATES), n=3)
        suggestion = f" Did you mean: {', '.join(close)}?" if close else ""
        return (
            f"{text!r} is not one of the predicate selectors the census emits."
            f"{suggestion} They are: {', '.join(sorted(PREDICATES))}."
        )
    if equals and not value:
        return f"{text!r} is a valued selector with no value"
    if equals and base == "schema.example" and value not in EXAMPLE_KINDS:
        return f"{text!r} is not one of the six example value kinds: {', '.join(sorted(EXAMPLE_KINDS))}."
    if equals and base not in VALUED:
        return f"{base!r} is not one of the fields that emit a valued selector. They are: {', '.join(sorted(VALUED))}."
    head, _, last = base.rpartition(".")
    if last.startswith("x-"):
        if head in prefixes:
            return None
        return f"{head!r} is not an object the census walks, so it declares no {last!r}"
    if base in selectors:
        return None
    close = difflib.get_close_matches(base, sorted(selectors), n=3)
    suggestion = f" Did you mean: {', '.join(close)}?" if close else ""
    return (
        f"{base!r} is not a selector of the OpenAPI object model.{suggestion} "
        "The grammar is docs/openapi-surface-coverage.md."
    )


_HTTP_METHODS = ("get", "put", "post", "delete", "options", "head", "patch", "trace")


def reference_counts(document: Any) -> Counter[str]:
    """How many times each `$ref` string is written anywhere in the document."""
    counts: Counter[str] = Counter()
    stack = [document]
    while stack:
        node = stack.pop()
        if isinstance(node, dict):
            reference = node.get("$ref")
            if isinstance(reference, str):
                counts[reference] += 1
            stack.extend(node.values())
        elif isinstance(node, list):
            stack.extend(node)
    return counts


def operation_routes(document: Any) -> dict[int, tuple[str, str]]:
    """`id()` of each Paths-Object operation -> its (HTTP method, Paths key)."""
    routes: dict[int, tuple[str, str]] = {}
    paths = document.get("paths") if isinstance(document, dict) else None
    for url, item in paths.items() if isinstance(paths, dict) else []:
        if not isinstance(item, dict) or not isinstance(url, str):
            continue
        for method in _HTTP_METHODS:
            if isinstance(item.get(method), dict):
                routes[id(item[method])] = (method, url)
    return routes


