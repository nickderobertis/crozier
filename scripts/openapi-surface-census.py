ONE, LIST, MAP = "one", "list", "map"


@dataclass(frozen=True)
class Child:
    """A field that carries further OpenAPI objects, and how they are held."""

    container: str
    kind: str


@dataclass(frozen=True)
class ObjectKind:
    """One OpenAPI object: which fields it declares and how a selector names it.

    `anchor` is the half of the selector grammar that cannot be derived from the
    specification: an anchor kind heads its own selector (`response.links`), and
    a non-anchor kind extends its parent's instead (`info.license.identifier`,
    `mediaType.encoding.headers`). The two lists are closed and are stated in
    `docs/openapi-surface-coverage.md`; they are here because the walk needs them.
    """

    name: str
    anchor: bool
    fields: dict[str, Child | None]
    free_map: Child | None = None


def _kind(
    name: str,
    anchor: bool,
    fields: dict[str, Child | None],
    free_map: Child | None = None,
) -> ObjectKind:
    return ObjectKind(name=name, anchor=anchor, fields=fields, free_map=free_map)


