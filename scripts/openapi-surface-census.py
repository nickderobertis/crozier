# The closed list of fields that also emit a valued selector, `<selector>=<value>`.
# A field is here when its value is drawn from a small, specification-defined set
# that a region needs to census one member of at a time (`parameter.in=cookie`);
# `schema.format` is here despite being an open set because a format is exactly
# the kind of shape a generator either maps to a Python type or drops.
VALUED = {
    "openapi.openapi", "parameter.in", "parameter.style", "header.style",
    "mediaType.encoding.style", "schema.type", "schema.format",
    "securityScheme.type", "securityScheme.in", "securityScheme.scheme",
}

# `$ref` inside these kinds is a declared field of the kind itself (a JSON Schema
# keyword, a Path Item reference); anywhere else a `$ref` makes the node a
# Reference Object, which is counted as one and not descended into.
REF_TRANSPARENT = {"schema", "pathItem"}


def grammar() -> tuple[set[str], set[str]]:
    """Every selector the grammar allows, and every prefix that can carry an `x-`.

    Enumerable because a selector is an anchor kind's name followed by a chain of
    fields through *extending* kinds only — the chain stops at the next anchor,
    which starts a selector of its own. That closed set is what makes a mistyped
    `--selector` refusable instead of silently reportable as undeclared.
    """
    selectors: set[str] = set()
    prefixes: set[str] = set()

    def visit(kind_name: str, prefix: str) -> None:
        if prefix in prefixes:
            return
        prefixes.add(prefix)
        kind = OBJECTS[kind_name]
        for field, child in kind.fields.items():
            selectors.add(f"{prefix}.{field}")
            if child is not None and not OBJECTS[child.kind].anchor:
                visit(child.kind, f"{prefix}.{field}")
        if kind.free_map is not None and not OBJECTS[kind.free_map.kind].anchor:
            visit(kind.free_map.kind, prefix)

    for name, kind in OBJECTS.items():
        if kind.anchor:
            visit(name, kind.name)
    return selectors, prefixes


def selector_error(text: str) -> str | None:
    """Why this `--selector` names nothing the grammar can emit, or None."""
    selectors, prefixes = grammar()
    base, equals, value = text.partition("=")
    if equals and not value:
        return f"{text!r} is a valued selector with no value"
    if equals and base not in VALUED:
        return (
            f"{base!r} is not one of the fields that emit a valued selector. "
            f"They are: {', '.join(sorted(VALUED))}."
        )
    head, _, last = base.rpartition(".")
    if last.startswith("x-"):
        if head in prefixes:
            return None
        return f"{head!r} is not an object the census walks, so it declares no {last!r}"
    if base in selectors:
        return None
    close = difflib.get_close_matches(base, sorted(selectors), n=3)
    suggestion = f" Did you mean: {', '.join(close)}?" if close else ""
    return (
        f"{base!r} is not a selector of the OpenAPI object model.{suggestion} "
        "The grammar is docs/openapi-surface-coverage.md."
    )


class Census:
    """One document's declaration-site counts, keyed by selector."""

    def __init__(self) -> None:
        self.counts: dict[str, int] = defaultdict(int)

    def record(self, selector: str) -> None:
        self.counts[selector] += 1

    def walk(self, node: Any, kind_name: str, prefix: str, seen: frozenset[int]) -> None:
        if not isinstance(node, dict):
            return
        if id(node) in seen:  # a YAML alias pointing back at an ancestor
            return
        seen = seen | {id(node)}
        kind = OBJECTS[kind_name]
        if "$ref" in node and kind_name not in REF_TRANSPARENT:
            reference = OBJECTS["reference"]
            for key in node:
                if isinstance(key, str) and key in reference.fields:
                    self.record(f"reference.{key}")
            return
        for key, value in node.items():
            if not isinstance(key, str):
                continue  # an unquoted status code or a numeric map key: a name
            if key.startswith("x-"):
                self.record(f"{prefix}.{key}")
                continue
            if key not in kind.fields:
                # Not a field of this object: either a name in a free-keyed map
                # (a path template, a status code, a property name) whose value is
                # still an OpenAPI object, or a key this specification does not
                # define, which declares no surface.
                if kind.free_map is not None:
                    self.descend(value, kind.free_map, prefix, seen)
                continue
            selector = f"{prefix}.{key}"
            self.record(selector)
            if selector in VALUED:
                for member in value if isinstance(value, list) else [value]:
                    if isinstance(member, (str, int, float)) and not isinstance(member, bool):
                        self.record(f"{selector}={self.value_of(selector, member)}")
            child = kind.fields[key]
            if child is not None:
                self.descend(value, child, selector, seen)

    @staticmethod
    def value_of(selector: str, member: str | int | float) -> str:
        text = str(member)
        if selector == "openapi.openapi":
            # The census cares about the 3.0-vs-3.1 delta, not the patch level.
            parts = text.split(".")
            return ".".join(parts[:2]) if len(parts) > 1 else text
        return text

    def descend(self, value: Any, child: Child, selector: str, seen: frozenset[int]) -> None:
        """Walk the objects a field carries, under the selector they head.

        An anchor kind heads its own selector; a non-anchor kind extends the
        field's. A free-keyed map hands its parent's selector straight through,
        which is how the property names, path templates and status codes that key
        those maps stay out of the census.
        """
        target = OBJECTS[child.kind]
        prefix = target.name if target.anchor else selector
        if child.container == MAP:
            values: Iterable[Any] = value.values() if isinstance(value, dict) else []
        else:
            # A single-object field holding a list (or a list field holding one
            # object) is common in real documents; traverse what is there rather
            # than what the specification promised.
            values = value if isinstance(value, list) else [value]
        for entry in values:
            self.walk(entry, child.kind, prefix, seen)


def census_document(document: Any) -> dict[str, int]:
    """Every `(selector, count)` one parsed source document declares."""
    census = Census()
    census.walk(document, "openapi", "openapi", frozenset())
    return dict(census.counts)


