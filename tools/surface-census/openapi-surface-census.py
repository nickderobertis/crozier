def enum_identifier(value: str, trace: set[str] | None = None) -> str:
    """The enum_words path of naming.rs, including its numeric and join rules.

    `trace`, when given, collects the branches of `enum_words` and
    `numeric_enum_identifier` this value takes that no other reading names: the
    deburr fold, each arithmetic range a spelled number falls in, a one-digit
    leading run, the two word-joining arms and the digit-boundary collapse. The
    `schema.enum:` predicates of the same names read it.
    """
    trace = set() if trace is None else trace
    folded = "".join(
        _ENUM_DEBURR_EXCEPTIONS[char]
        if char in _ENUM_DEBURR_EXCEPTIONS
        else unicodedata.normalize("NFKD", char).encode("ascii", "ignore").decode("utf-8")
        if "\u00c0" <= char <= "\u017f" and unicodedata.normalize("NFKD", char).encode("ascii", "ignore")
        else char
        for char in value
    )
    if folded != value:
        trace.add("deburred")
    uuid_parts = folded.split("-")
    if len(uuid_parts) == 5 and all(
        len(part) == size and all(char in "0123456789abcdefABCDEF" for char in part)
        for part, size in zip(uuid_parts, (8, 4, 4, 4, 12), strict=False)
    ):
        words = split_words(folded)
        if words:
            first = words[0]
            digits = len(first) - len(first.lstrip("0123456789"))
            if digits:
                words[0] = numeric_enum_name(int(first[:digits])) if digits == 1 else "undefined"
                if first[digits:]:
                    words.insert(1, first[digits:])
        collapsed = _collapse_enum_digit_boundaries("_".join(words))
        chars = list(collapsed)
        return "".join(
            char
            for index, char in enumerate(chars)
            if not (
                char == "_"
                and index >= 2
                and index + 2 < len(chars)
                and chars[index - 2].isdigit()
                and chars[index - 1].isascii()
                and chars[index - 1].isalpha()
                and chars[index + 1].isascii()
                and chars[index + 1].isalpha()
                and chars[index + 2].isdigit()
            )
        )
    if not folded:
        return "empty"
    whole = _WHOLE_VALUE_ENUM_WORDS.get(folded)
    if whole is None and folded.lower() == "n/a":
        whole = "not_applicable"
    if whole is not None:
        return whole
    # A zero-led value that is a number whole is spelled as that number.
    if len(folded) > 1 and folded[0] == "0" and folded.isascii() and folded.isdigit():
        number = int(folded)
        if number <= 9999:
            trace.add(_numeric_range(number))
            return numeric_enum_name(number)
    spaced = "".join("" if char in "'\u2019" else char if char.isascii() and char.isalnum() else " " for char in folded)
    words = split_words(spaced)
    value_leads_with_digit = bool(folded) and folded[0].isascii() and folded[0].isdigit()
    # Only a member *name* led by a zero-led digit run keeps the legal fallback:
    # a run the value itself starts with is spelled (`01_00_AM` is `ONE00AM`).
    leading_zero = (
        not value_leads_with_digit
        and "_" in folded
        and bool(words)
        and (len(words[0]) > 1 and words[0][0] == "0" and words[0].isascii() and words[0].isdigit())
    )
    if words:
        first = words[0]
        digits = len(first) - len(first.lstrip("0123456789"))
        if digits:
            number = first[:digits]
            spelled = None
            if value_leads_with_digit:
                significant = number.lstrip("0") or "0"
                if int(significant) <= 9999:
                    spelled = numeric_enum_name(int(significant))
                    trace.add(_numeric_range(int(significant)))
                elif len(folded.encode("utf-8")) > digits:
                    spelled = "undefined"
            elif len(number) <= 4 and (len(number) == 1 or number[0] != "0"):
                spelled = numeric_enum_name(int(number))
                trace.add(_numeric_range(int(number)))
            if spelled is not None and spelled != "undefined" and digits == 1:
                trace.add("single-digit-prefix")
            if spelled is not None:
                words[0] = spelled + ("_" + first[digits:] if first[digits:] else "")
    merged: list[str] = []
    previous_single = False
    for word in words:
        single = len(word) == 1 and word.isascii() and word.isalpha()
        if single and previous_single:
            merged[-1] += word
            trace.add("letter-run")
        else:
            merged.append(word)
        previous_single = single
    index = 1
    while index < len(merged):
        previous, current = merged[index - 1 : index + 1]
        short_letters = len(current) <= 2 and current.isascii() and current.isalpha()
        numeric_letter = (
            len(previous) > 1 and previous[-1].isalpha() and previous[:-1].isascii() and previous[:-1].isdigit()
        )
        single_letter = len(previous) == 1 and previous.isascii() and previous.isalpha()
        letter_digits = len(current) > 1 and current[0].isalpha() and current[1:].isascii() and current[1:].isdigit()
        if (short_letters and numeric_letter) or (single_letter and letter_digits):
            merged[index - 1] += merged.pop(index)
            trace.add("alphanumeric-join")
        else:
            index += 1
    identifier = "_".join(merged)
    if leading_zero:
        return identifier
    collapsed = _collapse_enum_digit_boundaries(identifier)
    if collapsed != identifier:
        trace.add("digit-boundary")
    return collapsed


