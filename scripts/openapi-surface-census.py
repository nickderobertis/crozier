# The closed list of *conjunction* selectors, the fourth kind — a shape that is a
# combination of fields rather than one field, written with the composition
# operators over the selectors above: `&` joins members declared at one
# object-model node, `>` descends into the object a field's value is, and `~>`
# descends into the schema the Reference Object at a group's last member denotes.
# A count is one per node at the leftmost position, exactly the count rule the
# three kinds above already have — one per *referencing* node under `~>`, never
# one per target.
#
# The list is closed because the cross-product of the grammar is not: four schema
# fields already spell fifteen non-empty combinations before nesting, and
# unbounded with it. What bounds this list instead is the branch structure of the
# six functions of `src/ir.rs` the goldens are blind to — a conjunction is worth
# enumerating iff two source documents differing only in it take different paths
# through one of `resolve_schema_pointer`, `nested_array_element`,
# `hoist_union_variant`, `ref_to_class`, `prop_type_ref` or `path_group`. Each
# entry below is read off one branch of one of those functions; the case analysis
# deriving them, and the enumeration holes for the branches no selector kind can
# express, are `docs/openapi-surface-coverage.md`'s
# `### The six blind regions of src/ir.rs, case by case`, which restates this
# table for a reader. `tests/surface_census_test.py` reconciles the two the way it
# already reconciles `VALUED` and `PREDICATES`.
#
# A branch earns a row only when a conjunction names it *exactly* — when the nodes
# this census counts and the nodes the generator sends down that branch differ
# only where another case of the same function claims them. That is what bounds
# the list to the entries below rather than to what the operators can spell: an
# arm reading something no member can say is a hole instead, and a row that
# pretended otherwise would count documents the generator sends elsewhere. Which
# properties a member can say is `PREDICATES`' business, not this table's — a
# collection's emptiness, an `enum`'s value types and which member of a `type`
# array comes first each have a predicate now, so the conditions those arms read
# compose here like any other member. An arm reading the *shape* of a `$ref`'s
# target is no longer a hole either: `~>` resolves the reference and the members
# after it read the target, which is what ten entries of this table do. Nor is an
# arm reading a pointer's segments *against* the document it points into: the five
