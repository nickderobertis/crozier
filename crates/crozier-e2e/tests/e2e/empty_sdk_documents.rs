/// tacd's `image/png:` with no value: invalid OpenAPI, the pair's empty SDK,
/// refused as `null-media-type` in a response and in a request body, while the
/// same document with an empty Media Type Object generates.
#[test]
fn a_null_media_type_is_refused_in_both_modes() {
    assert_log_records_false_success(
        "refusal-null-media-type",
        "fern.log",
        "Cannot read properties of null (reading 'schema')",
    );
    assert_eq!(
        file_count(&case_dir("refusal-null-media-type").join("fern-expected")),
        SCAFFOLD_FILES
    );
    assert_refused(
        &case_dir("refusal-null-media-type").join("openapi.yml"),
        "null-media-type",
        "paths//kiln/snapshot/get/responses/200/content/image/png",
    );
    let class = repo_root().join("docs/fern-refusals/null-media-type");
    assert_refused(
        &class.join("request-body-probe.yml"),
        "null-media-type",
        "paths//kiln/label/put/requestBody/content/text/plain",
    );
    // The same `null` in the `components.responses` or
    // `components.requestBodies` entry an operation's `$ref` names: the pair
    // empties both (`shapes.tsv`), and crozier refuses each where it is written.
    for (shape, element) in [
        (
            "component-response-probe.yml",
            "components/responses/Snapshot/content/image/png",
        ),
        (
            "component-request-body-probe.yml",
            "components/requestBodies/Label/content/text/plain",
        ),
    ] {
        let log = read(
            &class
                .join("evaluation-logs")
                .join(format!("fern-{}.log", shape.trim_end_matches("-probe.yml"))),
        );
        assert!(
            log.contains("generate exit: 0") && log.contains("Cannot read properties of null"),
            "{shape}: the pair's empty SDK is no longer recorded:\n{log}"
        );
        assert_refused(&class.join(shape), "null-media-type", element);
    }
    let temp = tempfile::tempdir().expect("output tempdir");
    let out = temp.path().join("sdk");
    probe_command(&class.join("empty-media-type-control.yml"), &out)
        .arg("--fern-strict")
        .assert()
        .success();
    // An operation the document ignores is never read, so its `null` entry
    // refuses nothing.
    let ignored = temp.path().join("ignored.yml");
    std::fs::write(
        &ignored,
        read(&case_dir("refusal-null-media-type").join("openapi.yml")).replace(
            "      operationId: getSnapshot\n",
            "      operationId: getSnapshot\n      x-fern-ignore: true\n",
        ),
    )
    .unwrap();
    assert!(read(&ignored).contains("x-fern-ignore: true"));
    let ignored_out = temp.path().join("ignored-sdk");
    probe_command(&ignored, &ignored_out)
        .arg("--fern-strict")
        .assert()
        .success();
    assert!(!read(&ignored_out.join("src/fern/client.py")).contains("get_snapshot"));
}

/// lolesports' shape is valid OpenAPI the pair empties only because its
/// example builder overflows; crozier generates it, in both enum modes, as
/// the tree `crozier-tree.tsv` records, while the pair generates the same
/// document with the property optional.
#[test]
fn a_required_self_reference_keeps_generating_under_the_valid_openapi_exception() {
    let dir = case_dir("R1");
    assert_log_records_false_success("R1", "fern.log", "Maximum call stack size exceeded");
    assert_eq!(file_count(&dir.join("fern-expected")), SCAFFOLD_FILES);
    let control = read(&dir.join("control.fern.log"));
    assert!(
        control.contains("generate exit: 0") && !control.contains("Failed to parse"),
        "the control's log must record a generation:\n{control}"
    );
    let manifest: Vec<(String, String)> = read(&dir.join("crozier-tree.tsv"))
        .lines()
        .skip(1)
        .map(|line| {
            let (path, digest) = line.split_once('\t').expect("path and digest");
            (path.to_owned(), digest.to_owned())
        })
        .collect();
    for (mode, strict) in [
        ("python-enums", false),
        ("python-enums", true),
        ("literals", false),
    ] {
        let temp = tempfile::tempdir().expect("output tempdir");
        let out = temp.path().join("sdk");
        let mut command = probe_command(&dir.join("openapi.yml"), &out);
        command.args(["--enum-type", mode]);
        if strict {
            command.arg("--fern-strict");
        }
        command.assert().success();
        let written: Vec<(String, String)> = walkdir(&out)
            .into_iter()
            .map(|path| {
                let relative = path
                    .strip_prefix(&out)
                    .unwrap()
                    .to_string_lossy()
                    .replace('\\', "/");
                let digest = super::sha256_hex(&std::fs::read(&path).unwrap());
                (relative, digest)
            })
            .collect();
        let mut written = written;
        written.sort();
        // Fern's literals tree carries no `core/enum.py`, and neither does crozier's.
        let expected: Vec<(String, String)> = manifest
            .iter()
            .filter(|(path, _)| mode == "python-enums" || path != "src/fern/core/enum.py")
            .cloned()
            .collect();
        assert_eq!(written, expected, "R1 ({mode}, strict {strict})");
        let shelf = read(&out.join("src/fern/types/shelf.py"));
        assert!(shelf.contains("parent_shelf"), "{shelf}");
    }
}

/// The SDK crozier writes for `case`, compared whole with the pair's tree.
fn matching(case: &str, strict: bool) -> (tempfile::TempDir, PathBuf, String) {
    let temp = tempfile::tempdir().expect("output tempdir");
    let out = temp.path().join("sdk");
    let spec = case_dir(case).join("openapi.yml");
    let mut command = probe_command(&spec, &out);
    if strict {
        command.arg("--fern-strict");
    }
    let output = command.output().expect("crozier runs");
    let stderr = String::from_utf8_lossy(&output.stderr).into_owned();
    assert!(output.status.success(), "{case}: {stderr}");
    let golden = format!("{EMPTY_SDK_DIR}/{case}/fern-expected");
    let ledger = departure_ledger()
        .golden(&golden, &[])
        .unwrap_or_else(|failures| panic!("{}", failures.join("\n")));
    let failures = golden_tree_failures(
        case,
        &spec.display().to_string(),
        &ledger,
        &repo_root().join(&golden),
        &out,
    );
    assert!(failures.is_empty(), "{case}: {}", failures.join("\n\n"));
    (temp, out, stderr)
}

/// A header `$ref` into another operation's response headers is resolved by
/// the pair, which generates the whole SDK; crozier now generates the same
/// tree, while the same pointer naming a header that does not exist stays
/// refused.
#[test]
fn a_header_pointer_into_paths_generates_fern_s_sdk() {
    let case = "crozier-refuses-path-pointer-ref";
    for strict in [false, true] {
        matching(case, strict);
    }
    let temp = tempfile::tempdir().expect("spec tempdir");
    let dangling = temp.path().join("openapi.yml");
    std::fs::write(
        &dangling,
        read(&case_dir(case).join("openapi.yml"))
            .replace("headers/X-Rate-Remaining'", "headers/X-Rate-Spent'"),
    )
    .unwrap();
    assert_refused(
        &dangling,
        "unresolved-reference",
        "#/paths/~1gauges/get/responses/200/headers/X-Rate-Spent",
    );
}

/// outstack/enveloper's shapes: each schema `$ref` naming a relative file that
/// does not exist is `typing.Any`, as the pair types it, with one warning per
/// reference naming the file and where it is written; and an inline body whose
/// discriminator maps to pointers outside `#/components/schemas/` is
/// `typing.Any` too. Both modes generate the pair's tree.
#[test]
fn a_missing_relative_schema_file_is_unknown_with_a_warning() {
    let case = "missing-relative-file";
    for strict in [false, true] {
        let (_temp, out, stderr) = matching(case, strict);
        for (pointer, file) in [
            (
                "#/paths/~1parcels/post/requestBody/content/application~1json/schema",
                "parcel.schema.yaml",
            ),
            (
                "#/paths/~1parcels/post/responses/202/content/application~1json/schema",
                "receipt.schema.yaml",
            ),
        ] {
            let line = stderr
                .lines()
                .find(|line| line.contains(pointer))
                .unwrap_or_else(|| panic!("no warning names {pointer}:\n{stderr}"));
            assert!(
                line.starts_with("crozier: warning: ")
                    && line.contains(&format!("generated{}{file}", std::path::MAIN_SEPARATOR))
                    && line.contains("which does not exist"),
                "{line}"
            );
        }
        // The `Components` block is no OpenAPI key, so nothing resolves its
        // entries and nothing warns of them.
        assert_eq!(stderr.matches("crozier: warning: ").count(), 2, "{stderr}");
        let client = read(&out.join("src/fern/client.py"));
        assert!(client.contains("request: typing.Any"), "{client}");
        let error = read(&out.join("src/fern/errors/bad_request_error.py"));
        assert!(error.contains("body: typing.Any"), "{error}");
        assert!(!out
            .join("src/fern/types/bad_request_error_body.py")
            .exists());
    }
    // A component that is itself a `$ref` to a missing file, whole or by
    // pointer, cannot form a type name; the pair refuses it with that class, and
    // so does crozier.
    for (stem, component) in [
        ("missing-relative-component", "Postmark"),
        ("missing-relative-component-pointer", "Stamp"),
    ] {
        let log = read(&case_dir(case).join(format!("{stem}.fern.log")));
        assert!(
            log.contains("Type name must begin with a letter"),
            "{stem}: the pair's refusal is no longer recorded:\n{log}"
        );
        assert_refused(
            &case_dir(case).join(format!("{stem}.yml")),
            "type-name-not-letter-led",
            component,
        );
    }
}

/// What stays an error: a missing file a security scheme, a response or a
/// parameter names is `unresolved-reference`; a file that exists but cannot be
/// read, and a remote document that cannot be fetched, keep their errors.
#[test]
fn other_missing_or_unreadable_references_still_fail() {
    let temp = tempfile::tempdir().expect("spec tempdir");
    let write = |name: &str, body: &str| {
        let path = temp.path().join(name);
        std::fs::write(&path, body).unwrap();
        path
    };
    let head = "openapi: 3.0.3\ninfo: {title: Postroom, version: '1'}\n";
    let operation = |extra: &str, schema: &str| {
        format!(
            "{head}paths:\n  /parcels:\n    get:\n      operationId: listParcels\n{extra}      responses:\n        '200':\n          description: OK\n          content:\n            application/json:\n              schema: {schema}\n"
        )
    };
    let security = write(
        "security.yml",
        &format!(
            "{}components:\n  securitySchemes:\n    Key:\n      $ref: './absent.yml#/Key'\nsecurity:\n  - Key: []\n",
            operation("", "{type: string}")
        ),
    );
    assert_refused(&security, "unresolved-reference", "./absent.yml#/Key");
    let response = write(
        "response.yml",
        &format!(
            "{head}paths:\n  /parcels:\n    get:\n      operationId: listParcels\n      responses:\n        '200':\n          $ref: './absent.yml#/Ok'\n"
        ),
    );
    assert_refused(&response, "unresolved-reference", "./absent.yml#/Ok");
    let parameter = write(
        "parameter.yml",
        &operation(
            "      parameters:\n        - $ref: './absent.yml#/Port'\n",
            "{type: string}",
        ),
    );
    assert_refused(&parameter, "unresolved-reference", "./absent.yml#/Port");

    std::fs::create_dir(temp.path().join("folder.yml")).unwrap();
    let unreadable = write("unreadable.yml", &operation("", "{$ref: './folder.yml'}"));
    let out = temp.path().join("sdk");
    probe_command(&unreadable, &out)
        .assert()
        .failure()
        .stderr(predicate::str::contains("could not read"));
    assert!(!out.exists());
    let remote = write(
        "remote.yml",
        &operation("", "{$ref: 'http://127.0.0.1:9/absent.yml#/Parcel'}"),
    );
    probe_command(&remote, &out)
        .assert()
        .failure()
        .stderr(predicate::str::contains("could not resolve remote $ref"));
    assert!(!out.exists());
}
