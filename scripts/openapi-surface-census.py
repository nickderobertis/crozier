def _is_digit(char: str) -> bool:
    return "0" <= char <= "9"


def _is_lower(char: str) -> bool:
    return "a" <= char <= "z"


def _is_upper(char: str) -> bool:
    return "A" <= char <= "Z"


def _is_alpha(char: str) -> bool:
    return _is_lower(char) or _is_upper(char)


def split_words(text: str) -> list[str]:
    """`naming::split_words`: lowercase words across camel, Pascal, snake and kebab."""
    words: list[str] = []
    current = ""
    chars = list(text)
    for index, char in enumerate(chars):
        if char in "_- .":
            if current:
                words.append(current)
                current = ""
            continue
        previous = chars[index - 1] if index else None
        following = chars[index + 1] if index + 1 < len(chars) else None
        boundary = (
            _is_upper(char)
            and bool(current)
            and (
                (previous is not None and (_is_lower(previous) or _is_digit(previous)))
                or (
                    previous is not None
                    and _is_upper(previous)
                    and following is not None
                    and _is_lower(following)
                )
            )
        )
        if boundary:
            words.append(current)
            current = ""
        # `to_ascii_lowercase` in Rust: a non-ASCII letter passes through unchanged.
        current += char.lower() if _is_upper(char) else char
    if current:
        words.append(current)
    return words


def to_snake_case(text: str) -> str:
    """`naming::to_snake_case`: a word after a digit-bearing word joins it."""
    out = ""
    for word in split_words(text):
        last = out.rsplit("_", 1)[-1]
        after_digit_word = (
            bool(out)
            and _is_digit(out[-1])
            and bool(last)
            and _is_digit(last[-1])
            and any(_is_alpha(char) for char in last)
        )
        if out and not after_digit_word:
            out += "_"
        out += word
    return out


def _fold_non_identifier(name: str) -> str:
    """`naming::fold_non_identifier`: every non-ASCII-alphanumeric is a boundary."""
    return "".join(
        char if (_is_alpha(char) or _is_digit(char)) else " " for char in name
    )


def _digit_suffix_absorbs_following(chars: list[str], digit_index: int) -> bool:
    """`naming::digit_suffix_absorbs_following`."""
    start = digit_index
    while start > 0 and _is_digit(chars[start - 1]):
        start -= 1
    if start > 0 and chars[start - 1] == "_":
        return True
    for char in reversed(chars[:start]):
        if char == "_":
            break
        if _is_alpha(char):
            return True
    return False


def _collapse_field_digit_boundaries(name: str) -> str:
    """`naming::collapse_field_digit_boundaries`: drop a digit-adjacent `_`."""
    chars = list(name)
    kept: list[str] = []
    for index, char in enumerate(chars):
        if char == "_" and (
            (
                index > 0
                and _is_digit(chars[index - 1])
                and _digit_suffix_absorbs_following(chars, index - 1)
            )
            or (index + 1 < len(chars) and _is_digit(chars[index + 1]))
        ):
            continue
        kept.append(char)
    return "".join(kept)


def _field_snake_case(wire_name: str) -> str:
    """`naming::field_snake_case`: whitespace chunks fold independently."""
    chunks = (
        _collapse_field_digit_boundaries(to_snake_case(_fold_non_identifier(chunk)))
        for chunk in wire_name.split()
    )
    return "_".join(chunk for chunk in chunks if chunk)


def is_reserved(name: str) -> bool:
    """`naming::is_reserved`: a Python keyword or a builtin Fern munges in fields."""
    return name in _PYTHON_KEYWORDS or name in _RESERVED_BUILTINS


def field_name(wire_name: str) -> str:
    """`naming::field_name`: the Python identifier crozier gives a wire name."""
    snake = _field_snake_case(wire_name)
    if snake and _is_digit(snake[0]):
        return f"f_{snake}"
    if is_reserved(snake):
        return f"{snake}_"
    return snake


def to_pascal_case(text: str) -> str:
    """`naming::to_pascal_case`: each word capitalized, and a letter after a digit."""
    out = ""
    for word in split_words(text):
        after_digit = False
        for index, char in enumerate(word):
            if index == 0 or (after_digit and _is_alpha(char)):
                # `to_ascii_uppercase` in Rust: a non-ASCII letter is unchanged.
                out += char.upper() if _is_lower(char) else char
            else:
                out += char
            after_digit = _is_digit(char)
    return out


# `naming::class_name` spells a leading digit out, so a schema name that starts
# with one still yields a legal class name (`5GmmCause` -> `FiveGmmCause`).
_DIGIT_WORDS = (
    "Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine",
)


def sanitize_identifier(name: str) -> str:
    """`naming::sanitize_identifier`: every other character becomes `_`."""
    out = "".join(
        char if (_is_alpha(char) or _is_digit(char) or char == "_") else "_"
        for char in name
    )
    if out and _is_digit(out[0]):
        out = f"_{out}"
    return out


def class_name(schema_key: str) -> str:
    """`naming::class_name`: the Python class name crozier gives a named schema."""
    pascal = to_pascal_case(schema_key)
    if pascal and _is_digit(pascal[0]):
        pascal = _DIGIT_WORDS[int(pascal[0])] + pascal[1:]
    return sanitize_identifier(pascal)


def normalized_path(template: str) -> str:
    """One Paths Object key with every template expression's name normalized.

    Only the names inside `{}` move: the literal segments, their order and their
    count are what distinguish two routes, so `/users/{userId}` normalizes to
    `/users/{user_id}` while `/{id}/users` and `/users/{id}` stay apart.
    """
    return _TEMPLATE_EXPRESSION.sub(
        lambda match: "{" + field_name(match.group(1)) + "}", template
    )


def primary_type(value: Any) -> str | None:
    """The `type` member `TypeField::primary` of `src/openapi.rs` reads.

    A string is its own primary type; a 3.1 list is the first member that is not
    `null`, which is why `type: [string, array]` takes the *string* path through
    every arm of `src/ir.rs` that asks whether a schema is an array. Anything else
    is a `type` crozier would refuse to deserialize, and reads as none here.
    """
    if isinstance(value, str):
        return value
    if isinstance(value, list):
        for member in value:
            if isinstance(member, str) and member != "null":
                return member
    return None


def string_valued(node: dict[Any, Any], values: Any) -> bool:
    """Whether `string_enum_values` of `src/ir.rs` would yield strings from these.

    Its three conditions, case for case: the schema is `type: string`, or it
    declares no `type` at all and every member is a string; and at least one member
    survives as a string, since a `type: string` enum whose members are integers
    leaves nothing to enumerate and crozier falls back to the base type.
    """
    if not isinstance(values, list):
        return False
    if primary_type(node.get("type")) != "string":
        omitted_type = "type" not in node
        all_strings = all(isinstance(value, str) for value in values)
        if not omitted_type or not all_strings:
            return False
    return any(isinstance(value, str) for value in values)


def path_segment_predicates(key: str) -> list[str]:
    """The three predicates `path_group` of `src/ir.rs` reads off one route.

    `path_group` splits the URL on `/`, drops the empty segments and returns the
    first that is not *wholly* a template expression, falling back to `service`
    when there is none. So a segment is templated here exactly as it is there —
    `{id}` is, `v{n}` is not — and the three arms partition every key: the first
    segment is literal, a later one is after `path_group` skipped a templated one,
    or there is none to find.
    """
    segments = [segment for segment in key.split("/") if segment]
    templated = [
        segment.startswith("{") and segment.endswith("}") for segment in segments
    ]
    if not any(not is_template for is_template in templated):
        return ["openapi.paths:all-segments-templated"]
    if templated[0]:
        return ["openapi.paths:template-before-literal-segment"]
    return ["openapi.paths:leading-literal-segment"]


# The prefix `ref_to_class` and `resolve_schema_pointer` both strip before they
# read a pointer's segments; a `$ref` that does not carry it takes the first case
# of either function, named off the value's last segment.
_COMPONENT_SCHEMAS_PREFIX = "#/components/schemas/"
# The three segments `ref_to_class` reads as a nesting step, and the composition
# spelling whose index it skips.
_COMPOSITION_SEGMENTS = ("allOf", "oneOf", "anyOf")


def pointer_form_predicates(reference: str) -> list[str]:
    """The predicates one `$ref` *value*'s own segment structure decides.

    `ref_to_class` of `src/ir.rs` opens no schema — it reads the reference string
    and nothing else — so its five cases are decided here, case for case, by
    walking the segments the way it does: `properties` with a segment after it
    consumes both, `items` consumes one, a composition keyword consumes its index,
    and anything else consumes one and contributes no name. Those read positions
    are `resolve_schema_pointer`'s too, which is why its case 8 (a segment none of
    the five names) and its case 1 (the reference is no component-schema pointer)
    are counted by the same spellings.

    Nothing here opens the schema a pointer addresses. Whether the pointer's head
    names a declared component is `Census.pointer_target_predicates`, which reads
    the document context; whether its later segments address the nesting the
    target declares is `pointer_walk_predicates` below, the resolving walk that
    closed what `docs/openapi-surface-coverage.md` recorded as H-pointer-nesting.
    """
    if not reference.startswith(_COMPONENT_SCHEMAS_PREFIX):
        # Case 1 of both functions, split by which of two shapes reached it: a
        # reference naming another document, which `helios-verifiable-api` writes
        # as an absolute URL and `ndw-accessibility-map` as a sibling file, and one
        # into this document outside `components.schemas`, which a Swagger
        # conversion writes as `#/definitions/Foo`. Both are declared by registered
        # sources; they are two spellings rather than one because only the first
        # names a document this instrument does not read.
        document, hash_mark, _ = reference.partition("#")
        if document or not hash_mark:
            return ["schema.$ref:cross-document"]
        return ["schema.$ref:same-document-foreign-pointer"]
    parts = reference[len(_COMPONENT_SCHEMAS_PREFIX):].split("/")
    found: set[str] = set()
    index = 1
    while index < len(parts):
        part = parts[index]
        if part == "properties" and index + 1 < len(parts):
            found.add("schema.$ref:nested-properties")
            index += 2
        elif part == "items":
            found.add("schema.$ref:nested-items")
            index += 1
        elif part in _COMPOSITION_SEGMENTS:
            found.add("schema.$ref:composition-index")
            index += 2
        else:
            # `ref_to_class`'s residual arm, which a trailing `properties` takes
            # too: with no segment after it there is no property name to append.
            found.add("schema.$ref:unnamed-segment")
            index += 1
    # One per node, whatever the repetition: a pointer carrying two `items`
    # segments selects the same arm twice and is one place the shape is written.
    return sorted(found)


# `usize::from_str` of Rust, which `resolve_schema_pointer` parses a composition
# index with: ASCII digits, optionally behind a `+`, and nothing else — a `-1`, a
# ` 1` or an empty segment is a parse error there and is one here.
_USIZE = re.compile(r"\+?[0-9]+")

# The five segment spellings `resolve_schema_pointer`'s `match part` names, and
# the arm each one selects. The value is the predicate the census records; the key
# is both the segment and the schema field the arm's body then reads, because the
# function's `match` arms and the OpenAPI fields they open are spelled alike.
_POINTER_WALK_ARMS = {
    "allOf": "schema.$ref:pointer-walk-reaches=allOf",
    "oneOf": "schema.$ref:pointer-walk-reaches=oneOf",
    "anyOf": "schema.$ref:pointer-walk-reaches=anyOf",
    "properties": "schema.$ref:pointer-walk-reaches=properties",
    "items": "schema.$ref:pointer-walk-reaches=items",
}


def _composition_members(value: Any) -> list[Any] | None:
    """One `allOf`/`oneOf`/`anyOf` value as the list `src/openapi.rs` reads it.

    `de_composition` accepts the array every document writes and also the
    integer-keyed *map* an importer sometimes emits, ordering it by key. A value
    that is neither is no composition, which is what `all_of.as_ref()?` answers
    `None` for.
    """
    if isinstance(value, list):
        return value
    if not isinstance(value, dict):
        return None
    indexed = []
    for key, member in value.items():
        if not isinstance(key, str) or not _USIZE.fullmatch(key):
            return None
        indexed.append((int(key), member))
    return [member for _, member in sorted(indexed, key=lambda pair: pair[0])]


def pointer_walk_predicates(reference: str, schemas: dict[Any, Any]) -> list[str]:
    """The arms `resolve_schema_pointer` enters walking this `$ref` through this document.

    The *other* of the two resolutions `src/ir.rs` performs, and the one nothing
    else in this census does: it requires the `#/components/schemas/` prefix,
    takes the component its **head** segment names, and then walks the remaining
    segments structurally through `allOf`, `oneOf`, `anyOf`, `properties` and
    `items`. `resolve_ref_from_schemas` — the last-segment lookup
    `schema.$ref:resolves-to-component` reads and the `~>` operator performs —
    traverses nothing and answers differently for every pointer carrying a segment
    after its head.

    An arm is recorded where the function *selects* it: on the segment its pattern
    names, before the arm's body asks whether the schema at that position declares
    the field. That is the placement `src/ir.rs`'s own `observed_arm!` sites have,
    and it is the arm's own condition — so `#/components/schemas/A/allOf/0` enters
    the `allOf` arm whether or not `A` declares an `allOf`, and a trailing
    `#/components/schemas/A/allOf` enters it too and then fails for want of an
    index. What decides whether a *later* segment's arm is reached is whether every
    earlier arm's body resolved, which is why this reading is a joint property of
    the reference value and the document it points into rather than of either
    alone.

    Three earlier `None`s stop the walk before any arm is selected, and each is a
    case of the same function's table: no `#/components/schemas/` prefix, a head
    naming no declared component, and a pointer carrying no segment after its head
    at all.

    One per node, whatever the repetition — the count rule every selector here
    has: a pointer carrying two `items` segments selects that arm twice and is one
    place the shape is written.
    """
    if not reference.startswith(_COMPONENT_SCHEMAS_PREFIX):
        return []
    parts = reference[len(_COMPONENT_SCHEMAS_PREFIX):].split("/")
    if len(parts) < 2:
        # `let mut next = Some(parts.next()?)`: a bare `#/components/schemas/Foo`
        # resolves to nothing, so the loop is never entered and no arm is selected.
        return []
    node = schemas.get(parts[0])
    if not isinstance(node, dict):
        return []  # `schemas.get(parts.next()?)?` — the head names no component
    found: set[str] = set()
    index = 1
    while index < len(parts):
        part = parts[index]
        arm = _POINTER_WALK_ARMS.get(part)
        if arm is None:
            break  # `_ => return None`, the residual arm
        found.add(arm)
        if part == "items":
            # `schema.items.as_deref()?`. `de_items` degrades a non-object into a
            # schema declaring nothing, so what stops a *later* segment is that
            # the field is unwritten, not that its value is odd.
            if not written(node, "items"):
                break
            child = node["items"]
            index += 1
        elif part == "properties":
            # `schema.properties.get(parts.next()?)?` — the key segment first, so
            # a trailing `properties` enters the arm and then fails.
            if index + 1 >= len(parts):
                break
            properties = node.get("properties")
            if not isinstance(properties, dict) or parts[index + 1] not in properties:
                break
            child = properties[parts[index + 1]]
            index += 2
        else:
            # `schema.all_of.as_ref()?.get(parts.next()?.parse::<usize>().ok()?)?`
            members = _composition_members(node.get(part))
            if members is None or index + 1 >= len(parts):
                break
            if not _USIZE.fullmatch(parts[index + 1]):
                break
            position = int(parts[index + 1])
            if position >= len(members):
                break
            child = members[position]
            index += 2
        node = child if isinstance(child, dict) else {}
    return sorted(found)


# The ten fields `is_unknown` of `src/ir.rs` reads, and the whole of what it reads.
# `type` is not among them because it is read through `TypeField::primary`, which a
# `type: [null]` satisfies without naming a type; `properties` is not, because an
# empty map is no declaration there.
_TYPE_DETERMINING_FIELDS = (
    "$ref", "oneOf", "anyOf", "allOf", "enum", "const", "additionalProperties", "items",
)


def written(node: dict[Any, Any], field: str) -> bool:
    """Whether this field is declared, the way `serde` reads one into an `Option`.

    A JSON `null` is not a declaration: `Option::<T>::deserialize` answers `None`
    for it, so `{"const": null}` reaches `src/ir.rs` with no `const` at all.
    """
    return field in node and node[field] is not None


def declares_nothing(node: Any) -> bool:
    """`is_unknown` of `src/ir.rs`: a schema carrying nothing that determines a type.

    Its ten conditions, case for case. A description, a title, a format, an
    example or an emptiness are all invisible to it, which is why the annotated-
    `$ref` shape accepts a member carrying any of them.
    """
    if not isinstance(node, dict):
        return False
    if any(written(node, field) for field in _TYPE_DETERMINING_FIELDS):
        return False
    if primary_type(node.get("type")) is not None:
        return False
    properties = node.get("properties")
    return not (isinstance(properties, dict) and properties)


def annotated_all_of_ref(node: dict[Any, Any]) -> bool:
    """`described_all_of_ref` of `src/ir.rs`, as a yes/no over one raw node.

    Its three conditions, case for case: the `allOf` holds at least two members;
    exactly one of them writes a `$ref` (a second returns `None` there, and none
    leaves nothing to annotate); and every member that does not write one
    `declares_nothing`. A member writing a `$ref` is read as the reference
    whatever else it writes, exactly as the Rust reads it — the `$ref` arm is
    tested first.
    """
    members = node.get("allOf")
    if not isinstance(members, list) or len(members) < 2:
        return False
    found = False
    for member in members:
        if not isinstance(member, dict):
            return False  # a document crozier refuses at the boundary
        if isinstance(member.get("$ref"), str):
            if found:
                return False
            found = True
        elif not declares_nothing(member):
            return False
    return found


# ---------------------------------------------------------------------------
# The discriminated-union reading
# ---------------------------------------------------------------------------
#
# Three predicates ask whether `discriminated_union` of `src/ir.rs` would build a
# union out of one Schema Object, which is a comparison *across* the members of
# one union rather than a property of the node in front of the walk: every member
# has to carry a value for one shared property, and those values have to be
# distinct. That is the family `operation.operationId:duplicate` is in, and the
# helpers below are the port of the Rust that decides it — `discriminant_value`,
# `string_enum_values`, `schema_example`, `inferred_discriminant_property_with`,
# `inferred_union_discriminant_property`, `discriminated_union` and
# `inheritance_discriminated_union`, case for case. A reading rather than a
# resemblance is the whole point: a `discriminator` written beside a `oneOf` is
# neither necessary nor sufficient for any of the three arms these predicates
# name.


def required_names(node: dict[Any, Any]) -> list[str]:
    """One schema's `required` array, as the `Vec<String>` `serde` reads it."""
    required = node.get("required")
    if not isinstance(required, list):
        return []
    return [name for name in required if isinstance(name, str)]


def string_enum_values(node: Any) -> list[str] | None:
    """`string_enum_values` of `src/ir.rs`: the strings it yields, or `None`.

    The `enum` array if one is written, else the one-member array its `const`
    falls back to, filtered to strings under the same three conditions
    `string_valued` above already ports — which is why this calls it rather than
    restating them.
    """
    if not isinstance(node, dict):
        return None
    if written(node, "enum"):
        values = node["enum"]
        if not isinstance(values, list):
            return None
    elif written(node, "const"):
        values = [node["const"]]
    else:
        return None
    if not string_valued(node, values):
        return None
    return [value for value in values if isinstance(value, str)]


def schema_example(node: dict[Any, Any]) -> Any:
    """`schema_example` of `src/ir.rs`: `example`, else the first of `examples`."""
    if written(node, "example"):
        return node["example"]
    examples = node.get("examples")
    if isinstance(examples, list) and examples:
        return examples[0]
    return None


def example_is_schema_definition(example: Any) -> bool:
    """`example_is_schema_definition` of `src/ir.rs`, condition for condition."""
    if not isinstance(example, dict) or not example:
        return False
    schema_keys = {"type", "$ref", "properties", "allOf", "oneOf", "anyOf"}
    return all(
        isinstance(value, dict) and bool(schema_keys & value.keys())
        for value in example.values()
    )


def discriminant_value(node: Any) -> str | None:
    """`discriminant_value` of `src/ir.rs`: the tag one member writes, or `None`.

    Two spellings and no others: a **one-member** string `enum` (or the `const`
    that stands in for one), or a string `example`. An `enum` of two strings is
    not a tag, and neither is a numeric one.
    """
    if not isinstance(node, dict):
        return None
    values = string_enum_values(node)
    if values is not None and len(values) == 1:
        return values[0]
    example = schema_example(node)
    return example if isinstance(example, str) else None


def union_members(node: dict[Any, Any]) -> list[Any] | None:
    """`one_of.as_ref().or(any_of.as_ref())` of `src/ir.rs`, over a raw node.

    `oneOf` wins wherever both are written, exactly as the `or` has it. A field
    written as something other than an array is a document crozier refuses at the
    boundary, and reads as no union here.
    """
    for field in ("oneOf", "anyOf"):
        if written(node, field):
            members = node[field]
            return members if isinstance(members, list) else None
    return None


# The values `inferred_discriminant_property_with` refuses to read as a
# `message_type` tag, which is `preserve_const_discriminant` of `src/ir.rs` and is
# its list rather than one invented here. The four property names that same
# function supports for a union referencing components are spelled in the `match`
# `_candidate_tag_values` mirrors below, where the Rust spells them, because each
# of the four asks something different of the member.
_PRESERVED_CONST_DISCRIMINANTS = frozenset({
    "approval", "approval_request_message", "message", "tool",
    "tool_return_message", "stop_reason", "usage_statistics",
})


def _resolved_member(member: Any, schemas: dict[Any, Any]) -> Any:
    """One union member as the *resolving* readers of it see it.

    `resolve_ref_from_schemas` is the last-segment lookup the `~>` operator
    already mirrors. `inferred_discriminant_property_with` falls back to the
    member itself where the lookup finds nothing (`unwrap_or(variant)`); the
    member loop of `discriminated_union` does not, and calls
    `_resolved_member_strict` instead.
    """
    if not isinstance(member, dict):
        return member
    reference = member.get("$ref")
    if not isinstance(reference, str):
        return member
    target = schemas.get(reference.rsplit("/")[-1])
    return target if isinstance(target, dict) else member


def _resolved_member_strict(member: Any, schemas: dict[Any, Any]) -> dict[Any, Any] | None:
    """One union member resolved, or `None` where `resolve_ref_from_schemas` fails."""
    if not isinstance(member, dict):
        return None
    reference = member.get("$ref")
    if not isinstance(reference, str):
        return member
    target = schemas.get(reference.rsplit("/")[-1])
    return target if isinstance(target, dict) else None


def _inferred_discriminant_property(
    node: dict[Any, Any], schemas: dict[Any, Any], enum_tag: bool = True
) -> str | None:
    """`inferred_discriminant_property_with` of `src/ir.rs`, condition for condition.

    The first resolved member's property *names* are the candidates, in the order
    it declares them, and a candidate wins when every resolved member carries a
    readable tag for it and the tags are all distinct. What "readable" means
    depends on whether the union references components at all: where it does, a
    member either tags itself with a required one-member `enum` or the property is
    one of the four `src/ir.rs` supports by name; where it does not, a one-member
    `enum` is required of every member.
    """
    members = union_members(node)
    if members is None:
        return None
    references_components = any(
        isinstance(member, dict) and isinstance(member.get("$ref"), str)
        for member in members
    )
    resolved = [_resolved_member(member, schemas) for member in members]
    if not resolved or not isinstance(resolved[0], dict):
        return None
    first_properties = resolved[0].get("properties")
    if not isinstance(first_properties, dict):
        return None
    for candidate in first_properties:
        if not isinstance(candidate, str):
            continue
        values = _candidate_tag_values(
            candidate, resolved, references_components, enum_tag
        )
        if values is not None and len(set(values)) == len(values):
            return candidate
    return None


def _candidate_tag_values(
    candidate: str,
    resolved: list[Any],
    references_components: bool,
    enum_tag: bool,
) -> list[str] | None:
    """The tag every resolved member writes for one candidate property, or `None`.

    One iteration of the `find_map` closure above: the `collect::<Option<Vec<_>>>`
    fails as soon as one member declares no readable tag, which is what a `None`
    here says.
    """
    values: list[str] = []
    for variant in resolved:
        if not isinstance(variant, dict):
            return None
        properties = variant.get("properties")
        field = properties.get(candidate) if isinstance(properties, dict) else None
        if not isinstance(field, dict):
            return None
        enum_written = field["enum"] if written(field, "enum") else None
        singleton_enum = len(string_enum_values(field) or []) == 1
        tagged_by_enum = (
            candidate in required_names(variant)
            and singleton_enum
            and isinstance(enum_written, list)
            and len(enum_written) == 1
        )
        if references_components and not (enum_tag and tagged_by_enum):
            if candidate == "type":
                supported = candidate in required_names(variant) and isinstance(
                    schema_example(field), str
                )
            elif candidate == "role":
                supported = candidate in required_names(variant)
            elif candidate in ("message_type", "mcp_server_type"):
                supported = True
            else:
                supported = False
            if not supported:
                return None
        elif not singleton_enum:
            return None
        value = discriminant_value(field)
        if value is None:
            return None
        if candidate == "message_type" and value in _PRESERVED_CONST_DISCRIMINANTS:
            return None
        values.append(value)
    return values


def _inferred_union_discriminant_property(
    node: dict[Any, Any], schemas: dict[Any, Any]
) -> str | None:
    """`inferred_union_discriminant_property` of `src/ir.rs`, with its fallback.

    The fallback reads `type` off every resolved member that requires it, and
    accepts either tag spelling `discriminant_value` reads. A union with no
    members at all satisfies it vacuously — nought distinct values out of nought —
    which is how an empty `oneOf: []` reaches `discriminated_union`'s `Some`.
    """
    found = _inferred_discriminant_property(node, schemas, True)
    if found is not None:
        return found
    members = union_members(node)
    if members is None:
        return None
    values: list[str] = []
    for member in members:
        variant = _resolved_member(member, schemas)
        if not isinstance(variant, dict) or "type" not in required_names(variant):
            return None
        properties = variant.get("properties")
        field = properties.get("type") if isinstance(properties, dict) else None
        value = discriminant_value(field)
        if value is None:
            return None
        values.append(value)
    return "type" if len(set(values)) == len(values) else None


def _mapping_targets_resolve(mapping: dict[Any, Any], schemas: dict[Any, Any]) -> bool:
    """`self.schemas.get(target_key)?`, over every entry of a written `mapping`."""
    for reference in mapping.values():
        if not isinstance(reference, str):
            return False
        if not isinstance(schemas.get(reference.rsplit("/")[-1]), dict):
            return False
    return True


def _written_discriminator(node: dict[Any, Any]) -> dict[Any, Any] | None:
    """The Discriminator Object this schema writes, as `Option<Discriminator>`."""
    discriminator = node.get("discriminator")
    return discriminator if isinstance(discriminator, dict) else None


def inheritance_union(node: dict[Any, Any], schemas: dict[Any, Any]) -> bool:
    """`inheritance_discriminated_union` of `src/ir.rs` returning `Some`.

    OpenAPI's other polymorphism spelling: a base object whose `discriminator`
    names its subtypes through a `mapping`, with no `oneOf` or `anyOf` of its own.
    Its three conditions are a `discriminator`, a non-empty `propertyName`, and a
    non-empty `mapping` every entry of which resolves.

    **One reading rather than a port.** The Rust lets a mapping entry naming the
    union's *own* coined class name through without resolving it — the wrapper
    holds the alias in a `value` field — and that name is coined from the call
    site rather than declared by the document, so no census can decide it. This
    requires every entry to resolve. The two disagree only on a mapping naming a
    component this document does not declare whose class name is nonetheless the
    one the caller would coin, which is a document contradicting itself; the case
    analysis records the divergence beside the case.
    """
    discriminator = _written_discriminator(node)
    if discriminator is None:
        return False
    property_name = discriminator.get("propertyName")
    if not isinstance(property_name, str) or not property_name:
        return False
    mapping = discriminator.get("mapping")
    if not isinstance(mapping, dict) or not mapping:
        return False
    return _mapping_targets_resolve(mapping, schemas)


def discriminated_union_head(node: dict[Any, Any], schemas: dict[Any, Any]) -> str | None:
    """Which composition head `discriminated_union` builds this union from, if any.

    `discriminated_union` of `src/ir.rs`, arm for arm, answering `"oneOf"`,
    `"anyOf"` or `None`:

    * a schema declaring neither is not this shape at all — it is the inheritance
      spelling, which `inheritance_union` above decides;
    * a `discriminator` written beside an `anyOf` with no `oneOf` is **refused**,
      because Fern applies an explicit discriminator to `oneOf` alone;
    * the discriminant property is the written `propertyName` where one is
      non-empty, and the *inferred* property otherwise — so a union carrying no
      `discriminator` at all reaches this;
    * where no non-empty `mapping` is written, every member — resolved first, if
      it is a `$ref` — must carry a `discriminant_value` for that property;
    * where one is, every mapping target must resolve.
    """
    if not written(node, "oneOf") and not written(node, "anyOf"):
        return None
    discriminator = _written_discriminator(node)
    if discriminator is not None and not written(node, "oneOf"):
        return None
    members = union_members(node)
    if members is None:
        return None
    property_name = None
    if discriminator is not None:
        declared = discriminator.get("propertyName")
        if isinstance(declared, str) and declared:
            property_name = declared
    if property_name is None:
        property_name = _inferred_union_discriminant_property(node, schemas)
    if property_name is None:
        return None
    mapping = discriminator.get("mapping") if discriminator is not None else None
    if isinstance(mapping, dict) and mapping:
        if not _mapping_targets_resolve(mapping, schemas):
            return None
    else:
        for member in members:
            target = _resolved_member_strict(member, schemas)
            if target is None:
                return None
            properties = target.get("properties")
            field = properties.get(property_name) if isinstance(properties, dict) else None
            if discriminant_value(field) is None:
                return None
    return "oneOf" if written(node, "oneOf") else "anyOf"


def components_schemas(document: Any) -> dict[Any, Any]:
    """One document's own `components.schemas` map, as the census reads it.

    The document being censused and nothing else: a `$ref` naming another document
    is a string to this instrument, never a fetch and never a second document.
    """
    if not isinstance(document, dict):
        return {}
    components = document.get("components")
    if not isinstance(components, dict):
        return {}
    schemas = components.get("schemas")
    return schemas if isinstance(schemas, dict) else {}


def grammar() -> tuple[set[str], set[str]]:
    """Every selector the grammar allows, and every prefix that can carry an `x-`.

    Enumerable because a selector is an anchor kind's name followed by a chain of
    fields through *extending* kinds only — the chain stops at the next anchor,
    which starts a selector of its own. That closed set is what makes a mistyped
    `--selector` refusable instead of silently reportable as undeclared.
    """
    selectors: set[str] = set()
    prefixes: set[str] = set()

    def visit(kind_name: str, prefix: str) -> None:
        if prefix in prefixes:
            return
        prefixes.add(prefix)
        kind = OBJECTS[kind_name]
        for field, child in kind.fields.items():
            selectors.add(f"{prefix}.{field}")
            if child is not None and not OBJECTS[child.kind].anchor:
                visit(child.kind, f"{prefix}.{field}")
        if kind.free_map is not None and not OBJECTS[kind.free_map.kind].anchor:
            visit(kind.free_map.kind, prefix)

    for name, kind in OBJECTS.items():
        if kind.anchor:
            visit(name, kind.name)
    return selectors, prefixes


def selector_error(text: str) -> str | None:
    """Why this `--selector` names nothing the grammar can emit, or None."""
    selectors, prefixes = grammar()
    if NEGATION in text:
        # A negated spelling is refused for what is wrong with it — an unanchored
        # complement, or a descent bound to a member the node does not write —
        # rather than reported as a shape nobody declares.
        malformed = conjunction_error(text)
        if malformed is not None:
            return malformed
    if is_conjunction(text) or NEGATION in text:
        # The conjunction list is closed by the branch structure of the six blind
        # functions, not by what the operators can spell, so a well-formed
        # combination nobody declared is refused exactly as a typo is.
        if text in CONJUNCTIONS:
            return None
        close = difflib.get_close_matches(text, sorted(CONJUNCTIONS), n=3)
        suggestion = f" Did you mean: {', '.join(close)}?" if close else ""
        return (
            f"{text!r} is not one of the conjunction selectors the census declares."
            f"{suggestion} The closed list of {len(CONJUNCTIONS)} is declared in "
            "scripts/openapi-surface-census.py and restated in "
            "docs/openapi-surface-coverage.md."
        )
    base, equals, value = text.partition("=")
    if ":" in base:
        # A predicate first, even when the spelling carries an `=`: the family
        # reads a member's *position* as well as its presence, so
        # `schema.type:primary=array` is one predicate's name rather than a valued
        # selector over a field called `schema.type:primary`.
        if text in PREDICATES:
            return None
        close = difflib.get_close_matches(text, sorted(PREDICATES), n=3)
        suggestion = f" Did you mean: {', '.join(close)}?" if close else ""
        return (
            f"{text!r} is not one of the predicate selectors the census emits."
            f"{suggestion} They are: {', '.join(sorted(PREDICATES))}."
        )
    if equals and not value:
        return f"{text!r} is a valued selector with no value"
    if equals and base == "schema.example" and value != "object":
        return (
            f"{text!r} is not the literal valued selector schema.example=object. "
            "The selected example value emits a valued selector only when it is an object."
        )
    if equals and base not in VALUED:
        return (
            f"{base!r} is not one of the fields that emit a valued selector. "
            f"They are: {', '.join(sorted(VALUED))}."
        )
    head, _, last = base.rpartition(".")
    if last.startswith("x-"):
        if head in prefixes:
            return None
        return f"{head!r} is not an object the census walks, so it declares no {last!r}"
    if base in selectors:
        return None
    close = difflib.get_close_matches(base, sorted(selectors), n=3)
    suggestion = f" Did you mean: {', '.join(close)}?" if close else ""
    return (
        f"{base!r} is not a selector of the OpenAPI object model.{suggestion} "
        "The grammar is docs/openapi-surface-coverage.md."
    )


class Census:
    """One document's declaration-site counts, keyed by selector."""

    def __init__(
        self,
        document: Any = None,
        conjunctions: dict[str, CompiledConjunction] | None = None,
    ) -> None:
        self.counts: dict[str, int] = defaultdict(int)
        # The conjunctions this walk evaluates: the closed list every command
        # line runs, unless a caller hands in its own. A caller doing that gets
        # this same evaluator over this same walk — which is how a conjunction
        # can be *proved* before the case it is read off has been derived, since
        # `tests/surface_census_test.py` holds the closed list to the cases the
        # blind-region tables carry.
        self.conjunctions = COMPILED_CONJUNCTIONS if conjunctions is None else conjunctions
        # The document context, reachable from every node this census walks: the
        # document's own `components.schemas` map and the set of its keys. It is
        # the document being censused and nothing else — no fetch, no
        # cross-document resolution, no second document — and a predicate may read
        # it, the way `schema.$ref:undeclared-component-head` compares a pointer's
        # head against the names below. A census built without one carries an
        # empty context rather than failing, so a caller measuring one node's
        # predicates in isolation still gets the node-local family.
        self.component_schemas: dict[Any, Any] = components_schemas(document)
        self.component_names: frozenset[str] = frozenset(
            key for key in self.component_schemas if isinstance(key, str)
        )
        # `operation.operationId:duplicate` compares one document's values against
        # each other, so it cannot be decided at the declaration site the way every
        # other selector is; the values are gathered here and counted by `finish`.
        self.operation_ids: list[str] = []
        # One node's own selectors are asked for twice — once to record them, once
        # per conjunction group matched against them — and a document's objects
        # live for the whole walk, so `id()` keys a stable cache.
        self.declared_cache: dict[tuple[int, str, str], list[str]] = {}

    def record(self, selector: str) -> None:
        self.counts[selector] += 1

    def declared_here(self, node: dict[Any, Any], kind_name: str, prefix: str) -> list[str]:
        """Every selector this one node declares, with repetition.

        The node's own reading of the grammar, and the only thing a conjunction
        group is ever matched against: a field it writes, the valued selector that
        field emits, an `x-` extension it carries, and the predicates this node
        alone decides. A Reference Object shadows its host's fields, exactly as the
        walk below reports it.
        """
        key = (id(node), kind_name, prefix)
        cached = self.declared_cache.get(key)
        if cached is not None:
            return cached
        kind = OBJECTS[kind_name]
        found: list[str] = []
        if kind_name == "paths":
            found += self.normalized_collisions(node)
            found += self.path_key_templates(node)
        if kind_name == "components":
            found += self.class_name_collisions(node.get("schemas"))
        if kind_name == "schema" and not is_reference_node(node, kind_name):
            found += self.schema_predicates(node)
            if isinstance(schema_example(node), dict):
                found.append("schema.example=object")
        if is_reference_node(node, kind_name):
            reference = OBJECTS["reference"]
            found += [
                f"reference.{name}"
                for name in node
                if isinstance(name, str) and name in reference.fields
            ]
            self.declared_cache[key] = found
            return found
        for name, value in node.items():
            if not isinstance(name, str):
                continue  # an unquoted status code or a numeric map key: a name
            if name.startswith("x-"):
                found.append(f"{prefix}.{name}")
                continue
            if name not in kind.fields:
                continue
            selector = f"{prefix}.{name}"
            found.append(selector)
            if kind_name == "operation" and name == "tags":
                if isinstance(value, list) and len(value) > 1:
                    found.append("operation.tags:multiple")
            if selector in VALUED:
                if selector == "schema.example":
                    continue
                for member in value if isinstance(value, list) else [value]:
                    if isinstance(member, bool):
                        # A boolean emits a valued selector only for the one field
                        # whose two booleans are two shapes; see `VALUED_BOOL`.
                        if selector in VALUED_BOOL:
                            found.append(f"{selector}={'true' if member else 'false'}")
                    elif isinstance(member, (str, int, float)):
                        found.append(f"{selector}={self.value_of(selector, member)}")
        self.declared_cache[key] = found
        return found

    def walk(self, node: Any, kind_name: str, prefix: str, seen: frozenset[int]) -> None:
        if not isinstance(node, dict):
            return
        if id(node) in seen:  # a YAML alias pointing back at an ancestor
            return
        seen = seen | {id(node)}
        kind = OBJECTS[kind_name]
        for selector in self.declared_here(node, kind_name, prefix):
            # `declared_here` answers what a node *declares*, which is what a
            # conjunction group is matched against; what a node declares and what
            # the census reports are the same everywhere except here. A member of
            # `MEMBER_ONLY_PREDICATES` is half a shape's name: standing alone it
            # would count nodes from which the generator function its arm belongs
            # to is never reached, so it is recorded only through the conjunctions
            # that carry that function's caller gate in front of it.
            if selector in MEMBER_ONLY_PREDICATES:
                continue
            self.record(selector)
        for selector, groups in self.conjunctions.items():
            # A fresh alias guard: a conjunction's descent is its own path from
            # this node, and the ancestors `seen` already holds are not on it.
            if self.conjunction_holds(node, kind_name, prefix, groups, 0, frozenset()):
                self.record(selector)
        if is_reference_node(node, kind_name):
            return
        for key, value in node.items():
            if not isinstance(key, str):
                # An unquoted status code or a numeric map key: a name, never a
                # field — so it declares no selector, exactly as `declared_here`
                # has it. But the object it *names* is still part of the surface,
                # so a free-keyed map is descended into here as it is below: a
                # Responses Object writing `200:` contributes what it would
                # contribute writing `"200":`, rather than losing its subtree.
                if kind.free_map is not None:
                    self.descend(value, kind.free_map, prefix, seen)
                continue
            if key.startswith("x-"):
                continue
            if key not in kind.fields:
                # Not a field of this object: either a name in a free-keyed map
                # (a path template, a status code, a property name) whose value is
                # still an OpenAPI object, or a key this specification does not
                # define, which declares no surface.
                if kind.free_map is not None:
                    self.descend(value, kind.free_map, prefix, seen)
                continue
            if kind_name == "operation":
                self.note_operation(key, value)
            child = kind.fields[key]
            if child is not None:
                self.descend(value, child, f"{prefix}.{key}", seen)

    def conjunction_holds(
        self,
        node: Any,
        kind_name: str,
        prefix: str,
        groups: CompiledConjunction,
        index: int,
        seen: frozenset[int],
        resolved: bool = False,
    ) -> bool:
        """Whether this conjunction's remaining groups hold from this node.

        The whole of what `&`, `!`, `>` and `~>` mean, and the only place any of
        them is interpreted: a group holds when every one of its positive members
        is a selector the node itself declares and none of its negated members
        is, `>` hands the groups after it to the objects the
        group's last member's value is, and `~>` hands them to the one schema the
        Reference Object written at that member denotes. A field holding several
        objects (a `oneOf` list, a `properties` map) satisfies the rest if any one
        of them does, which is what keeps the count one per node at the leftmost
        position — for both operators alike.

        `resolved` carries the reference-depth bound: an edge `~>` traverses is
        taken only from a node this descent reached *without* traversing one, so
        no chain of references is followed and no cycle among them can be walked
        round twice. The `seen | {id(node)}` guard below is the other half, and it
        guards a resolved edge exactly as it guards a written one.
        """
        if not isinstance(node, dict) or id(node) in seen:
            return False
        (positive, negated), descend = groups[index]
        declared = set(self.declared_here(node, kind_name, prefix))
        if not positive.issubset(declared) or negated & declared:
            return False
        if descend is None:
            return True
        descend, operator = descend
        if operator == RESOLVING_DESCENT:
            return self.resolving_descent_holds(node, descend, groups, index, seen, resolved)
        child = OBJECTS[kind_name].fields.get(descend)
        if child is None:
            return False
        value = node[descend]
        if child.container == MAP:
            entries: Iterable[Any] = value.values() if isinstance(value, dict) else []
        else:
            entries = value if isinstance(value, list) else [value]
        target = OBJECTS[child.kind]
        inner = target.name if target.anchor else f"{prefix}.{descend}"
        return any(
            self.conjunction_holds(
                entry, child.kind, inner, groups, index + 1, seen | {id(node)}, resolved
            )
            for entry in entries
        )

    def resolving_descent_holds(
        self,
        node: dict[Any, Any],
        field: str,
        groups: CompiledConjunction,
        index: int,
        seen: frozenset[int],
        resolved: bool,
    ) -> bool:
        """Whether the rest of this conjunction holds at what `~>` resolves to.

        The resolution is `resolve_ref_from_schemas` of `src/ir.rs` and not its
        neighbour `resolve_schema_pointer`: the reference's **last**
        `/`-separated segment, looked up in the document's own
        `components.schemas`, traversing nothing. That is the resolution the nine
        arms of `prop_type_ref`, `hoist_union_variant` and `nested_array_element`
        that read a `$ref`'s target actually call, and a descent mirroring the
        other one would count documents those arms never reach.

        Nothing is memoized: resolving is one `rsplit` and one dict lookup, with
        no traversal to repeat, so there is no work here to key by node identity
        the way `declared_cache` keys a node's own selectors.
        """
        if resolved:
            return False  # reference depth is one; see `conjunction_holds`
        reference = node.get(field)
        if not isinstance(reference, str):
            return False
        target = self.component_schemas.get(reference.rsplit("/")[-1])
        return self.conjunction_holds(
            target,
            "schema",
            OBJECTS["schema"].name,
            groups,
            index + 1,
            seen | {id(node)},
            True,
        )

    def note_operation(self, key: str, value: Any) -> None:
        """The document-scoped predicate one Operation Object's own fields feed."""
        if key == "operationId" and isinstance(value, (str, int, float)) and not isinstance(
            value, bool
        ):
            # Compared as written: a document that spells one id `1` and another
            # `"1"` has written the same value twice, and Fern reads both as a name.
            self.operation_ids.append(str(value))

    def normalized_collisions(self, node: dict[Any, Any]) -> list[str]:
        """`openapi.paths:normalized-collision`: keys crozier would render as one URL.

        One per colliding key rather than one per collision, so a document that
        writes the same normalized route twice contributes two and one that writes
        it three times contributes three. `x-` keys are extensions, not routes.
        """
        keys = self.route_keys(node)
        collisions: dict[str, int] = defaultdict(int)
        for key in keys:
            collisions[normalized_path(key)] += 1
        return [
            "openapi.paths:normalized-collision"
            for key in keys
            if collisions[normalized_path(key)] > 1
        ]

    def schema_predicates(self, node: dict[Any, Any]) -> list[str]:
        """The node-local predicates one Schema Object's own fields decide.

        Every one mirrors a property an arm of one of the six blind functions of
        `src/ir.rs` tests and no selector of the first two kinds can say: which
        member of a `type` array `TypeField::primary` reads, whether a
        `properties` map holds anything, how many non-`null` members a composition
        field has, and whether an `enum` or a `const` yields strings. Nothing here
        opens another node: a `$ref` is a *string* to this function, read for its
        own segment structure by `pointer_form_predicates` and for its head alone
        by `pointer_target_predicates`, and never followed to what it addresses.
        """
        found: list[str] = []
        primary = primary_type(node.get("type"))
        if primary == "array":
            found.append("schema.type:primary=array")
        if primary == "object":
            found.append("schema.type:primary=object")
        if primary in ("string", "number", "integer", "boolean"):
            found.append("schema.type:primary-scalar")
        all_of = node.get("allOf")
        if isinstance(all_of, list) and len(all_of) == 1:
            found.append("schema.allOf:sole-member")
        properties = node.get("properties")
        if isinstance(properties, dict) and properties:
            found.append("schema.properties:non-empty")
        for field in ("oneOf", "anyOf"):
            members = node.get(field)
            if not isinstance(members, list):
                continue
            non_null = [
                member
                for member in members
                if not isinstance(member, dict)
                or primary_type(member.get("type")) != "null"
            ]
            if len(non_null) == 1 and len(non_null) != len(members):
                found.append(f"schema.{field}:sole-non-null-member")
            if len(members) == 1:
                found.append(f"schema.{field}:sole-member")
        if "enum" in node and string_valued(node, node.get("enum")):
            found.append("schema.enum:string-valued")
        if "const" in node and string_valued(node, [node.get("const")]):
            found.append("schema.const:string-valued")
        if example_is_schema_definition(schema_example(node)):
            found.append("schema.example:schema-shaped")
        if annotated_all_of_ref(node):
            found.append("schema.allOf:annotated-ref")
        found += self.discriminated_union_predicates(node)
        reference = node.get("$ref")
        if isinstance(reference, str):
            found += pointer_form_predicates(reference)
            found += self.pointer_target_predicates(reference)
            found += self.resolving_target_predicates(reference)
            found += pointer_walk_predicates(reference, self.component_schemas)
        return found

    def discriminated_union_predicates(self, node: dict[Any, Any]) -> list[str]:
        """The three readings of `discriminated_union` this node's members decide.

        The one cross-member comparison in the grammar: a union is this shape only
        when its members, each resolved through the document context, all carry a
        distinct tag for one shared property — or when a written `mapping` names
        targets that all resolve. The three spellings are exclusive by
        construction, so no node counts twice: the inheritance one is decided only
        for a schema declaring neither composition field, and `oneOf` is the head
        wherever both are written.
        """
        if not written(node, "oneOf") and not written(node, "anyOf"):
            if inheritance_union(node, self.component_schemas):
                return ["schema.discriminator:inheritance-union"]
            return []
        head = discriminated_union_head(node, self.component_schemas)
        return [] if head is None else [f"schema.{head}:discriminated-union"]

    def resolving_target_predicates(self, reference: str) -> list[str]:
        """`schema.$ref:resolves-to-component`: the last-segment lookup finding one.

        The other of the two resolutions `src/ir.rs` performs, and the one `~>`
        mirrors: `resolve_ref_from_schemas` takes the reference's last
        `/`-separated segment and looks that name up in the document's own
        `components.schemas`, requiring no prefix and traversing nothing. An arm
        that needs only that a reference *resolve* — `hoist_union_variant`'s case
        6, which copies the target under a name of its own without reading a field
        of it — reads this; an arm that goes on to read the target's own fields is
        spelled with `~>`, which performs the same lookup and then descends.
        """
        if reference.rsplit("/")[-1] in self.component_names:
            return ["schema.$ref:resolves-to-component"]
        return []

    def pointer_target_predicates(self, reference: str) -> list[str]:
        """`schema.$ref:undeclared-component-head`: a head this document never declares.

        The one member of the pointer-form family that is not decided by the value
        alone. `resolve_schema_pointer`'s case 2 is `schemas.get(parts.next()?)?`
        returning `None`, so what selects it is the pointer's head segment measured
        against the document's own `components.schemas` keys — the same
        document-scope comparison `components.schemas:normalized-collision` makes
        over those keys, and the whole of what the document context is read for
        here.
        """
        if not reference.startswith(_COMPONENT_SCHEMAS_PREFIX):
            return []
        head = reference[len(_COMPONENT_SCHEMAS_PREFIX):].split("/")[0]
        if head in self.component_names:
            return []
        return ["schema.$ref:undeclared-component-head"]

    def path_key_templates(self, node: dict[Any, Any]) -> list[str]:
        """The five predicates the *shape* of a Paths Object key decides.

        `openapi.paths:templated-key` is one per key carrying a template
        expression at all, and `openapi.paths:several-template-expressions` one
        per key carrying more than one — two readings of the same key, so a key
        with three expressions contributes one to each and a key with one
        contributes to the first alone. The three `path_segment_predicates` adds
        are a third reading: not how many expressions a key carries but *where*
        the first one sits, which is the only thing `path_group` looks at.
        """
        found: list[str] = []
        for key in self.route_keys(node):
            expressions = len(_TEMPLATE_EXPRESSION.findall(key))
            if expressions:
                found.append("openapi.paths:templated-key")
            if expressions > 1:
                found.append("openapi.paths:several-template-expressions")
            found += path_segment_predicates(key)
        return found

    def class_name_collisions(self, node: Any) -> list[str]:
        """`components.schemas:normalized-collision`: names crozier renders as one class.

        The Paths Object counterpart above, on the other side of the same
        exclusion: a component name is a map key the grammar keeps out of the
        census as a *name*, so only a predicate can say two of them fold together
        under `naming::class_name`. One per colliding key, as there.
        """
        if not isinstance(node, dict):
            return []
        keys = [key for key in node if isinstance(key, str) and not key.startswith("x-")]
        collisions: dict[str, int] = defaultdict(int)
        for key in keys:
            collisions[class_name(key)] += 1
        return [
            "components.schemas:normalized-collision"
            for key in keys
            if collisions[class_name(key)] > 1
        ]

    @staticmethod
    def route_keys(node: dict[Any, Any]) -> list[str]:
        """The Paths Object keys that are routes: `x-` keys are extensions."""
        return [key for key in node if isinstance(key, str) and not key.startswith("x-")]

    def finish(self) -> None:
        """Record the predicates only the whole document decides."""
        written: dict[str, int] = defaultdict(int)
        for value in self.operation_ids:
            written[value] += 1
        for count in written.values():
            if count > 1:
                self.counts["operation.operationId:duplicate"] += count

    @staticmethod
    def value_of(selector: str, member: str | int | float) -> str:
        text = str(member)
        if selector == "openapi.openapi":
            # The census cares about the 3.0-vs-3.1 delta, not the patch level.
            parts = text.split(".")
            return ".".join(parts[:2]) if len(parts) > 1 else text
        return text

    def descend(self, value: Any, child: Child, selector: str, seen: frozenset[int]) -> None:
        """Walk the objects a field carries, under the selector they head.

        An anchor kind heads its own selector; a non-anchor kind extends the
        field's. A free-keyed map hands its parent's selector straight through,
        which is how the property names, path templates and status codes that key
        those maps stay out of the census.
        """
        target = OBJECTS[child.kind]
        prefix = target.name if target.anchor else selector
        if child.container == MAP:
            values: Iterable[Any] = value.values() if isinstance(value, dict) else []
        else:
            # A single-object field holding a list (or a list field holding one
            # object) is common in real documents; traverse what is there rather
            # than what the specification promised.
            values = value if isinstance(value, list) else [value]
        for entry in values:
            self.walk(entry, child.kind, prefix, seen)


def census_document(
    document: Any,
    conjunctions: dict[str, CompiledConjunction] | None = None,
) -> dict[str, int]:
    """Every `(selector, count)` one parsed source document declares."""
    census = Census(document, conjunctions)
    census.walk(document, "openapi", "openapi", frozenset())
    census.finish()
    return dict(census.counts)


