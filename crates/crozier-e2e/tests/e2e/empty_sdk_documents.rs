/// DigitalOcean's, dggs' and pro7.9's response `$ref` into another path, and
/// propresenter-remote's and Codat's parameter `$ref`: the pair writes its empty
/// SDK for each, and crozier refuses them as `unresolved-reference`.
#[test]
fn a_response_or_parameter_pointer_into_paths_is_refused_in_both_modes() {
    assert_log_records_false_success(
        "crozier-refuses-path-pointer-ref",
        "response-pointer.fern.log",
        "Failed to resolve #/paths/~1gauges/get/responses/404",
    );
    assert_refused(
        &case_dir("crozier-refuses-path-pointer-ref").join("response-pointer.yml"),
        "unresolved-reference",
        "#/paths/~1gauges/get/responses/404",
    );
    assert_log_records_false_success(
        "unresolved-reference",
        "fern.log",
        "Failed to resolve #/paths/~1gauges/get/parameters/0",
    );
    assert_eq!(
        file_count(&case_dir("unresolved-reference").join("fern-expected")),
        SCAFFOLD_FILES
    );
    assert_refused(
        &case_dir("unresolved-reference").join("openapi.yml"),
        "unresolved-reference",
        "#/paths/~1gauges/get/parameters/0",
    );
}

