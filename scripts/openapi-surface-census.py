def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="openapi-surface-census.py",
        description=(
            "Census the OpenAPI surface the registered golden sources declare, "
            "one row per (selector, fixture, count)."
        ),
    )
    parser.add_argument(
        "--fixture", action="append", default=[], metavar="NAME",
        help="census only this registered source (repeatable)",
    )
    parser.add_argument(
        "--selector", action="append", default=[], metavar="SELECTOR",
        help="report only this selector (repeatable); an undeclared one is reported as such",
    )
    parser.add_argument(
        "--vendored-only", action="store_true",
        help="census the vendored tests/fixtures sources alone (needs no network)",
    )
    parser.add_argument(
        "--allow-unfetched", action="store_true",
        help="warn instead of failing when a link-ok source has not been fetched",
    )
    parser.add_argument("--json", action="store_true", help="emit the census as JSON")
    parser.add_argument("--fixtures-root", type=Path, metavar="DIR")
    parser.add_argument("--corpus-root", type=Path, metavar="DIR")
    return parser.parse_args(argv)


def path_of(source: Source, repo_root: Path) -> str | None:
    """A source's document path as the JSON report carries it."""
    if source.path is None:
        return None
    if source.path.is_relative_to(repo_root):
        return source.path.relative_to(repo_root).as_posix()
    return str(source.path)


def report(rows: dict[tuple[str, str], int], selectors: list[str]) -> str:
    """The census as one line per (selector, fixture, count)."""
    lines: list[str] = []
    width = max((len(selector) for selector, _ in rows), default=0)
    width = max(width, *(len(s) for s in selectors)) if selectors else width
    fixture_width = max((len(fixture) for _, fixture in rows), default=0)
    for selector, fixture in sorted(rows):
        lines.append(f"{selector.ljust(width)}  {fixture.ljust(fixture_width)}  {rows[(selector, fixture)]:>5}")
    declared = {selector for selector, _ in rows}
    for selector in selectors:
        if selector not in declared:
            lines.append(f"{selector.ljust(width)}  (declared by no registered source)")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    repo_root = Path(__file__).resolve().parent.parent
    fixtures_root = args.fixtures_root or repo_root / "tests" / "fixtures"
    corpus_root = args.corpus_root or repo_root / ".local" / "corpus"
    if not fixtures_root.is_dir():
        print(f"openapi-surface-census: missing fixtures root {fixtures_root}", file=sys.stderr)
        return 1

    for selector in args.selector:
        problem = selector_error(selector)
        if problem is not None:
            print(f"openapi-surface-census: {problem}", file=sys.stderr)
            return 1

    sources = registered_sources(fixtures_root, corpus_root, args.vendored_only)
    if args.fixture:
        wanted = set(args.fixture)
        known = {source.fixture for source in sources}
        unknown = sorted(wanted - known)
        if unknown:
            print(
                f"openapi-surface-census: no registered source is named {unknown[0]!r}. "
                "The registered sources are the tests/fixtures/<name>/openapi.* documents "
                "and the link-ok rows of tests/fixtures/CORPUS.md.",
                file=sys.stderr,
            )
            return 1
        sources = [source for source in sources if source.fixture in wanted]

    unfetched = [source.fixture for source in sources if source.path is None]
    if unfetched and not args.allow_unfetched:
        print(
            f"openapi-surface-census: {len(unfetched)} registered source(s) have not been "
            f"fetched, starting with {unfetched[0]!r}, so the census would report them as "
            "declaring nothing. Run 'scripts/fetch-corpus.sh' (or 'just surface-census', "
            "which fetches first), or pass --vendored-only to census the offline half.",
            file=sys.stderr,
        )
        return 1
    for fixture in unfetched:
        print(f"openapi-surface-census: warning: {fixture} is unfetched", file=sys.stderr)

    rows: dict[tuple[str, str], int] = {}
    censused: list[Source] = []
    for source in sources:
        if source.path is None:
            continue
        try:
            document = load_document(source.path)
        except DocumentError as error:
            print(f"openapi-surface-census: {source.fixture}: {error}", file=sys.stderr)
            return 1
        if not isinstance(document, dict):
            print(
                f"openapi-surface-census: {source.fixture}: {source.path} is not an "
                "OpenAPI document (its root is not a mapping)",
                file=sys.stderr,
            )
            return 1
        censused.append(source)
        for selector, count in census_document(document).items():
            if args.selector and selector not in args.selector:
                continue
            rows[(selector, source.fixture)] = count

    if args.json:
        payload = {
            "sources": [
                {
                    "fixture": source.fixture,
                    "origin": source.origin,
                    # POSIX-style inside the repo so the report reads the same on
                    # every platform of the release matrix; null when the source is
                    # a link-ok row nothing has fetched.
                    "path": path_of(source, repo_root),
                }
                for source in sources
            ],
            "rows": [
                {"selector": selector, "fixture": fixture, "count": count}
                for (selector, fixture), count in sorted(rows.items())
            ],
            "absent_selectors": sorted(
                selector
                for selector in args.selector
                if selector not in {declared for declared, _ in rows}
            ),
        }
        print(json.dumps(payload, indent=2, sort_keys=False))
    else:
        rendered = report(rows, args.selector)
        if rendered:
            print(rendered)

    vendored = sum(1 for source in censused if source.origin == "vendored")
    print(
        f"openapi-surface-census: {len({selector for selector, _ in rows})} selector(s), "
        f"{sum(rows.values())} declaration site(s) across {len(censused)} source(s) "
        f"({vendored} vendored, {len(censused) - vendored} fetched)",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
